async function download(source) {
  const response = await fetch(source.url); assert.ok(response.ok, `${source.url}: ${response.status}`);
  const data = Buffer.from(await response.arrayBuffer());
  assert.equal(createHash('sha256').update(data).digest('hex'), source.sha256, source.url);
  return data;
}
async function digest(image) {
  const info = JSON.parse(execFileSync('buildx', ['imagetools', 'inspect', image, '--format', '{{json .Manifest}}'], {encoding:'utf8'}));
  return image.replace(/(:[^/:]+)?(@sha256:[a-f0-9]+)?$/, '') + '@' + info.digest;
}
