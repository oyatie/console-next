-- The comparable position of a value: the integer, 0/1 for a bool, the
-- 0-based index in the strictest-first code list. NULL when the value is not
-- of the key's kind. Mirrors SettingDef::parse + SettingDef::ordinal.
CREATE FUNCTION setting_ordinal(p_kind TEXT, p_codes TEXT[], p_value JSONB)
RETURNS BIGINT
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
    SELECT CASE
        WHEN p_kind = 'int' AND jsonb_typeof(p_value) = 'number'
             AND p_value::TEXT ~ '^-?[0-9]{1,18}$'
            THEN p_value::TEXT::BIGINT
        WHEN p_kind = 'bool' AND jsonb_typeof(p_value) = 'boolean'
            THEN CASE WHEN p_value = 'true'::JSONB THEN 1 ELSE 0 END
        WHEN p_kind = 'code' AND jsonb_typeof(p_value) = 'string'
            THEN array_position(p_codes, p_value #>> '{}') - 1
    END
$$;

-- The D0.3 onboarding test: no employees and no applied payroll run, so no
-- decision was made under the old value. One definition for the trigger and
-- the application's pre-check. SECURITY INVOKER: the trigger (row_security
-- off) sees every row of the org; the runtime role, armed to its own org, sees
-- only its own rows, so asking about another org reveals nothing.
CREATE FUNCTION tenant_setting_onboarding(p_org UUID)
RETURNS BOOLEAN
LANGUAGE sql STABLE
SET search_path = public, pg_temp
AS $$
    SELECT NOT EXISTS (SELECT 1 FROM employees e WHERE e.org_id = p_org)
       AND NOT EXISTS (
           SELECT 1 FROM payroll_draft_runs r
            WHERE r.org_id = p_org
              AND r.status IN ('APPROVED', 'DISBURSEMENT_SCHEDULED', 'PAID', 'ISSUED'))
$$;

CREATE TABLE tenant_setting_overrides (
    -- RESTRICT, not CASCADE: platform_force_remove_direct_org_children sweeps
    -- only RESTRICT/NO ACTION children of organizations, and it must clear
    -- these rows before users go (set_by is RESTRICT). The append-only trigger
    -- admits that DELETE under app.platform_force_remove_org.
    org_id               UUID        NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    id                   UUID        NOT NULL DEFAULT gen_random_uuid(),
    -- NULL = tenant-wide; otherwise the legal entity or 사업장. No FK yet:
    -- no legal-entity/사업장 table exists at be8e38d (org_units are
    -- departments, branches are 지점). INT-FOUND-MIG picks the target.
    scope_entity_id      UUID        NULL,
    key                  TEXT        NOT NULL,
    value                JSONB       NOT NULL,
    effective_from       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Set by the trigger; any value the caller sends is overwritten.
    direction            TEXT        NOT NULL DEFAULT 'neutral'
                             CHECK (direction IN ('tighten', 'loosen', 'neutral')),
    onboarding_exempt    BOOLEAN     NOT NULL DEFAULT false,
    set_by               UUID        NOT NULL,
    reason_code          TEXT        NOT NULL CHECK (btrim(reason_code) <> ''),
    reason_note          TEXT        NULL
                             CHECK (reason_note IS NULL OR (btrim(reason_note) <> '' AND char_length(reason_note) <= 1000)),
    -- The step-up assertion that authorised a loosening (BW-29 owns the kinds).
    step_up_assertion_id UUID        NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, id),
    UNIQUE NULLS NOT DISTINCT (org_id, key, scope_entity_id, effective_from),
    FOREIGN KEY (set_by, org_id) REFERENCES users (id, org_id) ON DELETE RESTRICT
);

CREATE FUNCTION tenant_setting_overrides_check()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
-- Function-scoped (restored on exit): the onboarding probe and the in-force
-- lookup must see every row of NEW.org_id, not only the caller's RLS view.
SET search_path = public, pg_temp
SET row_security = off
AS $$
DECLARE
    d          RECORD;
    new_ord    BIGINT;
    cur_value  JSONB;
    cur_ord    BIGINT;
    looser     BOOLEAN;
BEGIN
    SELECT * INTO d FROM setting_definition(NEW.key);
    IF d.kind IS NULL THEN
        RAISE EXCEPTION 'setting_unknown_key' USING ERRCODE = '23514', DETAIL = NEW.key;
    END IF;
    IF d.governance <> 'tenant' THEN
        RAISE EXCEPTION 'setting_not_editable' USING ERRCODE = '23514', DETAIL = NEW.key;
    END IF;

    new_ord := setting_ordinal(d.kind, d.codes, NEW.value);
    IF new_ord IS NULL THEN
        RAISE EXCEPTION 'setting_value_invalid' USING ERRCODE = '23514', DETAIL = NEW.key;
    END IF;
    IF d.kind = 'int' AND (new_ord < d.min_value OR new_ord > d.max_value) THEN
        RAISE EXCEPTION 'setting_out_of_range' USING ERRCODE = '23514', DETAIL = NEW.key;
    END IF;
    IF NEW.effective_from < now() THEN
        RAISE EXCEPTION 'setting_backdated' USING ERRCODE = '23514', DETAIL = NEW.key;
    END IF;

    -- The value this row replaces: in force at effective_from, entity row
    -- first, then the tenant row, then the code default.
    SELECT o.value INTO cur_value
      FROM tenant_setting_overrides o
     WHERE o.org_id = NEW.org_id
       AND o.key = NEW.key
       AND o.effective_from <= NEW.effective_from
       AND (o.scope_entity_id IS NULL OR o.scope_entity_id = NEW.scope_entity_id)
     ORDER BY (o.scope_entity_id IS NULL), o.effective_from DESC
     LIMIT 1;
    cur_ord := COALESCE(setting_ordinal(d.kind, d.codes, cur_value), d.default_ordinal);

    looser := CASE
        WHEN d.looser_when = 'neutral' THEN false
        -- First declaration of a directional fact.
        WHEN cur_ord IS NULL THEN true
        WHEN d.looser_when = 'higher' THEN new_ord > cur_ord
        ELSE new_ord < cur_ord
    END;
    NEW.direction := CASE
        WHEN looser THEN 'loosen'
        WHEN d.looser_when = 'neutral' OR new_ord = cur_ord THEN 'neutral'
        ELSE 'tighten'
    END;
    NEW.onboarding_exempt := false;

    IF looser AND NEW.effective_from < now() + interval '24 hours' THEN
        IF NOT tenant_setting_onboarding(NEW.org_id) THEN
            RAISE EXCEPTION 'setting_loosening_delay' USING ERRCODE = '23514', DETAIL = NEW.key;
        END IF;
        NEW.onboarding_exempt := true;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_tenant_setting_overrides_check
    BEFORE INSERT ON tenant_setting_overrides
    FOR EACH ROW EXECUTE FUNCTION tenant_setting_overrides_check();

CREATE FUNCTION tenant_setting_overrides_append_only()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE'
       AND current_setting('app.platform_force_remove_org', true) = 'on' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION
        'tenant_setting_overrides is append-only: % is forbidden (row id=%)',
        TG_OP, OLD.id
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER trg_tenant_setting_overrides_append_only
    BEFORE UPDATE OR DELETE ON tenant_setting_overrides
    FOR EACH ROW EXECUTE FUNCTION tenant_setting_overrides_append_only();

