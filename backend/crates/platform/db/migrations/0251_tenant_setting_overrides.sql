-- BW-00 (= BW-27) tenant settings registry: append-only, effective-dated
-- override rows (decisions D0.3). Numbered head+1 of the lane's base; INTEG
-- renumbers it at the batch merge (tools/integ/renumber-migrations.sh), which
-- also rewrites the include_str! in crates/settings/domain/tests/sql_definitions.rs.
--
-- 1. Keys, kinds, bounds, risk directions and governance are code-defined in
--    console-settings-domain. setting_definition() below is GENERATED from
--    that roster and pinned by a test, so the trigger and the Rust check
--    cannot drift. No reference rows: the function body is the registry.
-- 2. A BEFORE INSERT trigger, not a CHECK (a now()-based CHECK breaks
--    dump/restore), enforces:
--    - the key exists and has a tenant override path;
--    - the value is of the key's kind and inside its code range (legal
--      floors and ceilings are encoded as the range, with the code default
--      on the bound, so they can only be tightened);
--    - effective_from >= now(): never back-dated;
--    - a loosening (relative to the value in force at effective_from, at the
--      row's scope) takes effect no earlier than now() + 24 hours, unless the
--      tenant is onboarding (no employees, no applied payroll run), in which
--      case it applies immediately and onboarding_exempt records it.
--    The trigger also records the direction, which drives the loosening
--    notice. Who may change what, and step-up, are Cedar's (OD-12).
-- 3. Resolution order: legal entity or 사업장 (scope_entity_id) -> tenant
--    (scope_entity_id NULL) -> code default. Platform-only and read-only keys
--    have no rows (code default only in the MVP).
SET LOCAL lock_timeout = '2s';

