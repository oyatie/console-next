-- BE-MIG (walkthrough W11, W12; decisions #27, #28).
--
-- 1. W11: the employee import apply runs as a job. `apply_job` is the job the
--    apply route started (state, digest, requester, rows done / total, the
--    report or the refusal); `apply_heartbeat_at` is when a driver last wrote
--    it, so the schedule loop resumes a job whose process died. Both are
--    written by the runtime role; the 0166 writer guard still refuses any
--    console_rt write of status APPLIED, apply_summary or applied_*.
-- 2. W12: an employee roster has no pay period. 0224 made the period NOT NULL
--    so no upload acquires a period nobody chose; that stays true for every
--    other import (attendance), now as a CHECK. An employee_hr run may carry
--    none (never a default); such a run is never payroll material, because
--    the payroll roster writer (payroll adapter roster.rs) scopes by period
--    equality. A workbook meant for a payroll month still declares it.
-- 3. W12: `data_import_row_phones`, the 휴대전화 of an import row between
--    preview and apply, as E.164. Phone headers are restricted (never in a
--    raw row, 0247/0249), so the number is staged apart like the sealed RRN
--    (0296): moved to the employment profile by the settle, deleted with it,
--    purged with the staged identities after `import.staged_identity.ttl_days`.
-- 4. `import.apply.max_rows` (registry key, #28: 2,000 rows, headroom 3,000):
--    setting_definition() regenerated from the roster.

ALTER TABLE data_import_runs
    ADD COLUMN apply_job JSONB NULL,
    ADD COLUMN apply_heartbeat_at TIMESTAMPTZ NULL,
    ADD CONSTRAINT data_import_runs_apply_job_shape CHECK (
        apply_job IS NULL OR (
            jsonb_typeof(apply_job) = 'object'
            AND apply_job->>'state' IN ('queued', 'applying', 'settling', 'done', 'failed')
        )
    );

CREATE INDEX idx_data_import_runs_apply_job_running
    ON data_import_runs (org_id, apply_heartbeat_at)
    WHERE apply_job->>'state' IN ('queued', 'applying', 'settling');

COMMENT ON COLUMN data_import_runs.apply_job IS
    'pd:none — structural or non-personal attribute of a non-person row; the apply job of an employee import run (state, counts, report or refusal code), no person values';
COMMENT ON COLUMN data_import_runs.apply_heartbeat_at IS
    'pd:none — structural or non-personal attribute of a non-person row; when an apply driver last wrote the job';

ALTER TABLE data_import_runs
    ALTER COLUMN pay_period_start DROP NOT NULL,
    ALTER COLUMN pay_period_end DROP NOT NULL,
    ADD CONSTRAINT data_import_runs_pay_period_required CHECK (
        entity_type = 'employee_hr'
        OR (pay_period_start IS NOT NULL AND pay_period_end IS NOT NULL)
    ),
    ADD CONSTRAINT data_import_runs_pay_period_both CHECK (
        (pay_period_start IS NULL) = (pay_period_end IS NULL)
    );

CREATE TABLE data_import_row_phones (
    org_id     UUID        NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    run_id     UUID        NOT NULL,
    source_key TEXT        NOT NULL CHECK (btrim(source_key) <> ''),
    phone_e164 TEXT        NOT NULL CHECK (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, run_id, source_key),
    FOREIGN KEY (run_id, org_id) REFERENCES data_import_runs (id, org_id) ON DELETE CASCADE
);
CREATE INDEX data_import_row_phones_age_idx ON data_import_row_phones (org_id, created_at);

ALTER TABLE data_import_row_phones ENABLE ROW LEVEL SECURITY;
ALTER TABLE data_import_row_phones FORCE ROW LEVEL SECURITY;
CREATE POLICY org_isolation ON data_import_row_phones
    USING (org_id = NULLIF(current_setting('app.current_org', true), '')::uuid)
    WITH CHECK (org_id = NULLIF(current_setting('app.current_org', true), '')::uuid);
REVOKE ALL PRIVILEGES ON data_import_row_phones FROM PUBLIC, console_rt;
GRANT SELECT, INSERT, DELETE ON data_import_row_phones TO console_rt;

