제9조 보유·반환·파기와 재위탁
고객사는 관계 법령에 따른 보존 의무를 고려하여 보유기간을 정해야 합니다. 근로자 명부와 근로계약 등은 근로기준법 제42조 및 같은 법 시행령 제22조의 보존 의무를 따릅니다. 회사는 고객사의 지시와 위탁 계약에 따라 반환·파기에 협조하며, 법정 보존이 필요한 정보는 보존 사유와 기간을 구분하여 관리해야 합니다.
현재 보유기간이 지난 퇴직자 기록의 자동 파기와 계약 종료 후 모든 사본의 파기 기한은 확정되지 않았습니다. 감사 기록과 백업의 제한은 제2조와 같습니다. 회사와 고객사는 처리위탁 계약에서 보유·반환·파기 절차를 정해야 합니다.
회사는 제3조의 저장·통신 제공자를 이용합니다. 고객사 정보를 재위탁하거나 국외로 이전할 때에는 법령 및 위탁 계약에 따른 고지·동의와 보호조치를 적용해야 하며, 이 문서 확인이 고객사의 재위탁·국외 이전 절차를 대신하지 않습니다.

제10조 고객사 임직원의 권리 행사
임직원은 개인정보처리자인 고객사에 자기 인사 정보의 열람, 정정·삭제 및 처리정지를 요구할 수 있습니다. 서비스에서 제공하는 인사 정보 정정 요청은 고객사 담당자가 처리합니다. 회사가 직접 요구를 받으면 해당 고객사와 협의하여 법령상 요구 처리에 협조합니다. 회사의 수탁 업무에도 제4조의 보호조치를 적용합니다.

