<a id="a15"></a>
## 제15조 정보주체와 법정대리인의 권리·의무 및 행사 방법

1. 정보주체는 회사에 언제든지 개인정보의 열람, 정정·삭제, 처리정지, 동의 철회를 요구할 수 있고(「개인정보 보호법」 제35조부터 제37조까지), 자동화된 결정이 있는 경우 그 거부와 설명을 요구할 수 있습니다(제37조의2).
2. **요구 방법:** 서면, 전자우편 또는 전화로 [제17조](#a17)의 부서에 요구할 수 있습니다. 「개인정보 처리 방법에 관한 고시」 별지 제8호(열람요구서) 등의 서식을 이용할 수 있습니다. 회사는 요구 방법을 개인정보 수집 방법보다 어렵게 정하지 않습니다(제38조제4항, 시행령 제41조제2항).
   - 서비스 화면: 【확인 필요: 서비스 안의 요구 경로(메뉴 위치). 개인정보를 서비스 화면에서 수집하므로, 최소한 같은 창구로도 요구할 수 있어야 합니다(시행령 제41조제2항제2호). 현재 서비스에는 본인이 직접 열람·삭제·처리정지·동의 철회를 요구하는 기능이 없습니다(facts §9). 게시 전에 경로를 마련해야 합니다.】
   - 전자우편: 【확인 필요 Q3】
   - 전화: 【확인 필요 Q3】
   - 서면: 【확인 필요 Q1: 회사 주소】
3. **처리 기한:** 회사는 요구한 사람이 본인이거나 정당한 대리인인지 확인한 뒤, 요구를 받은 날부터 10일 이내에 조치하고 결과를 알립니다(시행령 제41조제4항, 제43조제3항, 제44조제2항).
4. **대리인:** 법정대리인이나 위임을 받은 사람을 통하여 요구할 수 있습니다. 이 경우 위임장(개인정보 처리 방법에 관한 고시 별지 제11호)을 제출해야 합니다(시행령 제45조).
5. **제한:** 다음의 경우에는 요구가 제한될 수 있으며, 회사는 그 사유를 알립니다.
   - 열람: 법률에 따라 열람이 금지되거나 제한되는 경우, 다른 사람의 생명·신체를 해칠 우려가 있거나 재산과 그 밖의 이익을 부당하게 침해할 우려가 있는 경우 등(제35조제4항).
   - 삭제: 다른 법령에서 그 개인정보를 수집 대상으로 명시하고 있는 경우(제36조제1항 단서).
   - 처리정지: 법률에 특별한 규정이 있거나 법령상 의무를 지키기 위하여 불가피한 경우 등(제37조제2항).
6. **이의 제기:** 회사가 요구를 거절하거나 일부만 받아들이는 등의 조치에 불복하는 경우 이의를 제기할 수 있도록 다음 절차를 둡니다(제38조제5항). 결과를 받은 날부터 【확인 필요: 기간】 이내에 [제17조](#a17)의 부서에 이의를 제기할 수 있고, 회사는 이의를 받은 날부터 【확인 필요: 회사가 정할 처리 기한. 법령에 정해진 기한은 없음】 이내에 다시 검토하여 결과를 알립니다. 【확인 필요: 이의 처리 절차 확정】
7. **수수료:** 회사는 열람 등 요구에 수수료를 받지 않습니다. 【확인 필요: 결정. 받는다면 실비 범위에서 정하며, 요구의 원인이 회사에 있으면 받을 수 없습니다(시행령 제47조).】
8. 고객사 임직원의 인사 정보에 관한 요구는 [제23조](#b5)를 보십시오.

<a id="a16"></a>
## 제16조 자동화된 결정

회사는 완전히 자동화된 시스템으로 정보주체의 권리나 의무에 중대한 영향을 미치는 결정을 하지 않습니다. 【확인 필요: 근태·휴가 등에서 사람의 판단 없이 자동으로 거부·확정하는 기능이 생기면 시행령 제44조의4제1항의 사항을 이 조에 추가합니다.】

