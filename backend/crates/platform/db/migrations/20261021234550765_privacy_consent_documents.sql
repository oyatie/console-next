# 제1부. 회사가 개인정보처리자로서 처리하는 개인정보

<a id="a1"></a>
## 제1조 개인정보의 처리 목적

회사는 다음 목적으로만 개인정보를 처리합니다. 목적이 바뀌면 「개인정보 보호법」 제18조에 따라 별도의 동의를 받는 등 필요한 조치를 합니다.

1. **서비스 계정 관리:** 고객사가 지정한 관리자·인사 담당자·구성원의 계정 생성, 본인 확인(최초 로그인 일회용 코드, 패스키), 로그인 상태 유지, 권한 부여·변경·말소 기록.
2. **서비스 이용계약의 체결과 이행:** 고객사 관리자의 이용약관 및 개인정보 처리 안내 확인 기록 관리. 【확인 필요: 요금 청구·결제를 서비스에서 처리하는지 여부. 처리한다면 목적과 항목을 추가합니다.】
3. **법령상 안전조치 의무 이행과 보안:** 개인정보처리시스템 접속기록의 작성·보관·점검, 부정 접속과 오남용 방지, 장애 확인과 대응.
4. **고객 지원:** 회사 지원 담당자가 읽기 전용으로 고객사 화면을 확인하고, 그 지원 이력을 감사 기록에 남기는 일. 【확인 필요: 고객사의 요청이나 동의가 있을 때만 화면을 확인하는 운영 절차가 있는지(코드에는 읽기 전용 제한만 있고 요청·동의 확인 장치는 없음), 고객사가 그 지원 이력을 서비스에서 직접 볼 수 있는지】
5. **회사 운영자의 운영 도구 접근 통제:** 회사 소속 운영자가 운영 도구에 접근할 때 본인 확인.

회사는 서비스에서 마케팅·광고 목적으로 개인정보를 처리하지 않습니다.

