회사는 개인정보 처리에 관한 업무를 총괄하고, 정보주체의 불만 처리와 피해 구제를 위하여 다음과 같이 개인정보 보호책임자와 담당 부서를 지정합니다. 열람 요구도 아래 부서에서 접수·처리합니다.

