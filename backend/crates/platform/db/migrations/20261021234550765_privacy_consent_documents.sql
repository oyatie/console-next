ALTER TABLE auth_refresh_token_families ADD COLUMN privacy_acceptance JSONB;
COMMENT ON COLUMN auth_refresh_token_families.privacy_acceptance IS
    'pd:personal — cached exact document references and acceptance timestamp for this account session';

-- Restore proof once per family, never scan audit history on an app write.
CREATE FUNCTION auth_family_privacy_cache() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    SELECT after_snap || jsonb_build_object('accepted_at', occurred_at)
      INTO NEW.privacy_acceptance FROM audit_events
     WHERE org_id=NEW.org_id AND actor=NEW.user_id AND action='privacy.required_accept'
       AND target_type='privacy_terms' AND after_snap ? 'privacy' AND after_snap ? 'terms'
     ORDER BY occurred_at DESC LIMIT 1;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_auth_family_privacy_cache BEFORE INSERT ON auth_refresh_token_families
    FOR EACH ROW EXECUTE FUNCTION auth_family_privacy_cache();
