2. **자동 삭제:** 등록을 취소한 직원의 개인정보는 고객사가 정한 기간(기본 30일, 0~30일) 뒤 자동으로 삭제합니다. 가져오기 중 임시 보관한 주민등록번호와 전화번호는 [제20조](#b2)의 기간 뒤 자동으로 삭제합니다.
3. **퇴직자 기록:** 퇴직한 임직원의 기록은 고객사의 지시에 따라 파기합니다. 【확인 필요 Q11: 현재 서비스에는 보유 기간이 지난 퇴직자 기록을 파기하는 기능이 없습니다. 출시 전에 파기 절차를 정해야 합니다.】
4. **계약 종료:** 고객사와의 계약이 끝나면 고객사의 선택에 따라 개인정보를 돌려주거나 파기하며, 계약 종료 후 【확인 필요: 기한(일)】 이내에 파기합니다. 백업에 남는 기간은 [제5조](#a5)제3항과 같습니다.
5. 파기 방법은 [제5조](#a5)와 같습니다.

<a id="b4"></a>
## 제22조 재위탁

회사는 [제8조](#a8)의 수탁자에게 업무를 다시 위탁합니다. 재수탁자를 추가하거나 바꿀 때에는 「개인정보 보호법」 제26조제6항에 따라 고객사의 동의를 받습니다. 고객사는 자기 처리방침의 위탁 공개(같은 조 제2항)에 이 목록을 연결할 수 있습니다.

고객사 임직원의 개인정보도 [제9조](#a9)와 같이 Cloudflare의 국외 네트워크를 거칩니다. 이 이전에는 개인정보처리자인 고객사의 국외 이전 근거와 공개(같은 법 제28조의8)가 필요하며, 회사도 수탁자로서 같은 조의 보호조치를 지킵니다(같은 법 제26조제8항). 【법률 검토 C-2: 고객사가 쓸 이전 근거와 위탁 계약 조항】

<a id="b5"></a>
## 제23조 고객사 임직원의 권리 행사

1. 고객사의 임직원 등은 자기 인사 정보의 열람, 정정·삭제, 처리정지 등을 개인정보처리자인 고용주, 즉 **고객사**에게 요구할 수 있습니다.
2. 서비스에서는 이름, 전화번호, 입사일, 고용 형태, 직위, 기본급에 대한 정정 요청을 할 수 있으며, 고객사의 인사 담당자가 처리합니다. 요청한 본인은 자기 요청을 승인할 수 없습니다.
3. 회사에 직접 요구가 들어오면 회사는 【확인 필요: 기한(일)】 이내에 해당 고객사에 전달하고, 고객사의 지시에 따라 요구 처리에 협조합니다. 【법률 검토 C-3: 제26조제8항이 제35조~제38조를 수탁자에게 준용하므로, 회사가 직접 답변해야 하는 범위를 정하고 위탁 계약에 반영해야 합니다.】

<a id="b6"></a>
## 제24조 안전성 확보조치와 보호책임자

고객사를 위하여 처리하는 개인정보에도 [제10조](#a10)의 안전성 확보조치를 똑같이 적용합니다. 수탁 업무에 관한 문의는 [제17조](#a17)의 개인정보 보호책임자와 담당 부서가 처리합니다.

