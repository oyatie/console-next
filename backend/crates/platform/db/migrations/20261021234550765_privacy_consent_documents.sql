**민감정보:** 고객사가 입력한 경우 장애 정도(중증·경증)와 인정일, 보훈 대상 구분과 인정일을 처리합니다. 보훈 대상 구분은 상이(傷痍) 여부를 드러낼 수 있어 건강에 관한 정보로 다룹니다. 고객사는 정보주체의 별도 동의(「개인정보 보호법」 제23조제1항제1호) 또는 법령(같은 항 제2호, 【확인 필요: 「장애인고용촉진 및 직업재활법」·「국가유공자 등 예우 및 지원에 관한 법률」의 해당 조항】)을 근거로 입력하며, 서비스는 어느 근거인지와 동의 일자를 함께 기록합니다. 【확인 필요: 장애·보훈 정보가 다른 이용자의 화면(조직도, 프로필 등)에 표시되는지. 표시된다면 [제11조](#a11)에 공개 가능성과 비공개 선택 방법을 적어야 합니다.】

**고유식별정보(주민등록번호):** 【확인 필요 Q4: 출시 시 주민등록번호 수집 기능을 사용할지. 현재 운영 환경에서는 사용하지 않습니다.】 이 기능을 사용하면 고객사가 따르는 법령(「개인정보 보호법」 제24조의2제1항제1호, 【확인 필요: 근거 법령과 서식】)에 따라서만 처리하며, 별도의 키로 암호화하고, 기본 화면에는 앞 7자리만 표시하며, 전체 번호를 조회하려면 조회 사유를 입력해야 하고 그 조회는 접속기록에 남습니다. 엑셀 가져오기 중 임시로 보관한 주민등록번호는 고객사가 정한 기간(기본 7일, 1~30일) 뒤 자동으로 삭제합니다.

**저장하지 않는 정보:** 계좌번호, 신분증 번호, 운전면허번호, 병역 면제 사유는 저장하지 않습니다.

**14세 미만 아동:** 가족 사항에 14세 미만 자녀의 이름과 생년월일이 포함될 수 있습니다. 이 정보는 고객사가 【확인 필요: 근거 법령(예: 「소득세법」)】에 따라 입력하며, 회사는 아동에게서 직접 수집하지 않습니다.

