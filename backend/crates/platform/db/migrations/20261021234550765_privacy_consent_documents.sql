<a id="a10"></a>
## 제10조 개인정보의 안전성 확보조치

회사는 「개인정보 보호법」 제29조, 시행령 제30조와 「개인정보의 안전성 확보조치 기준」(개인정보보호위원회 고시 제2026-9호)에 따라 다음 조치를 하고 있습니다.

1. **내부 관리계획:** 【확인 필요: 내부 관리계획 수립·시행 여부, 개인정보취급자 교육 주기】
2. **접근 권한 관리:** 역할과 범위에 따라 업무에 필요한 최소한의 권한만 부여하고, 권한의 부여·변경·말소 기록을 3년 이상 보관합니다. 회사 지원 담당자의 고객사 화면 확인은 읽기 전용입니다.
3. **접근 통제:** 패스키로 로그인하며, 일정 시간(기본 30분) 동안 사용하지 않으면 자동으로 로그아웃됩니다. 운영 서버에는 공인 IP 주소가 없고, 관리 접속은 접근이 통제된 경유 서버로만 가능합니다. 웹 방화벽과 과다 요청 차단을 운영합니다.
4. **암호화:** 인터넷 구간의 통신은 암호화(TLS)합니다. 저장 장치, 파일 저장소, 비밀정보는 하드웨어 보안 모듈(HSM)에서 관리하는 AES-256 키로 암호화합니다. 데이터베이스 백업은 AES-256으로 암호화합니다. 주민등록번호를 처리하는 경우 별도의 키로 한 번 더 암호화하고, 기본 화면에는 앞 7자리만 표시합니다.
5. **접속기록의 보관과 점검:** 개인정보를 조회할 때마다 조회한 사람, 일시, 접속지, 조회 대상, 수행 업무를 기록하고 2년 이상 보관합니다. 감사 기록은 추가만 가능하며 수정하거나 삭제할 수 없습니다. 개인정보를 파일(CSV)로 내려받으려면 이용 목적을 선택해야 하며, 내려받은 기록이 남습니다. 【확인 필요: 접속기록과 내려받기 기록을 점검하는 주기·방법·사후 조치(「개인정보의 안전성 확보조치 기준」 제8조제2항에 따라 내부 관리계획으로 정함)】
6. **악성 프로그램 방지와 취약점 관리:** 서버 보안 기준(CIS)을 적용하고, 클라우드 보안 감시와 취약점 점검을 운영합니다. 【확인 필요: 서버와 개인정보취급자 업무용 기기에 악성프로그램 방지 프로그램을 설치·갱신하는지(시행령 제30조제1항제6호)】
7. **물리적 조치:** 서버와 저장 장치는 Oracle Cloud Infrastructure 데이터센터에 있으며, 데이터센터의 물리적 보안은 Oracle이 관리합니다. 【확인 필요: 회사 사무실과 업무용 기기의 물리적 보호조치】
8. **고객사 간 분리:** 데이터베이스의 행 단위 보안 정책으로 고객사별 데이터에 다른 고객사가 접근할 수 없게 합니다.

> 【확인 필요 Q4, Q6】 과거 가져오기 감사 기록에 주민등록번호가 평문으로 남아 있을 수 있습니다(마이그레이션 0249 주석). 처리 방침이 정해지기 전에는 "주민등록번호는 모두 암호화한다"라고 쓰지 않았습니다.

