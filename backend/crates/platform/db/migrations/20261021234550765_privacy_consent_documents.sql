## 제5조 개인정보의 파기 절차 및 방법

1. **파기 절차:** 회사는 보유 기간이 끝났거나 처리 목적이 달성된 개인정보를 확인하고, 개인정보 보호책임자의 승인을 받아 파기합니다. 【확인 필요: 파기 대상 확인 주기와 파기 기록 방법】
2. **파기 방법:** 전자적 파일은 복원이 불가능한 방법으로 영구 삭제합니다(시행령 제16조제1항제1호). 「개인정보의 안전성 확보조치 기준」 제13조에 따라 완전파괴(소각·파쇄 등), 전용 소자장비를 이용한 삭제, 또는 데이터가 복원되지 않도록 초기화하거나 덮어쓰는 방법으로 파기합니다. 일부만 삭제하는 경우에는 삭제한 개인정보가 복구·재생되지 않도록 관리·감독합니다(같은 조 제2항). 회사는 서비스와 관련하여 개인정보를 종이 문서로 처리하지 않습니다. 【확인 필요】
3. **백업에 남는 기간:** 삭제한 개인정보는 암호화된 데이터베이스 백업에 최대 35일(주기상 최대 7일 추가) 동안 남고, 백업 저장소의 이전 버전은 42일 뒤 자동으로 삭제됩니다. 주 1회 만드는 저장 볼륨 백업은 최근 2회분만 보관합니다. 회사는 백업을 장애 복구 목적으로만 사용합니다. 【확인 필요: 데이터베이스 변경 기록(WAL) 보관분의 보존 기간이 정해져 있지 않음(facts §5). 직원 사진 복제 저장소(`mnt-evidence-replica`)의 보존 기간(Q10). 두 기간이 정해지기 전에는 "최대 35일"이 모든 사본에 대한 약속이 되지 않습니다.】
4. **다른 법령에 따라 보존하는 경우:** 보유 기간이 끝났어도 다른 법령에 따라 보존해야 하는 개인정보는 다른 개인정보와 분리하여 저장·관리합니다(「개인정보 보호법」 제21조제3항). 보존하는 항목과 근거는 [제4조](#a4)의 표와 같습니다. 【확인 필요: 분리 보관 방식 구현 여부】

