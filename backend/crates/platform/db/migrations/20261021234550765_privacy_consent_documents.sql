<a id="part-b"></a>
# 제2부. 회사가 수탁자로서 처리하는 개인정보

<a id="b1"></a>
## 제19조 회사의 지위

1. 회사는 고객사로부터 인사·조직 관리 업무를 위탁받아, 고객사 임직원 등의 개인정보를 **수탁자로서** 처리합니다. 이 개인정보의 개인정보처리자는 각 고객사입니다. 수탁자에게도 처리방침의 수립·공개 의무가 준용되므로(「개인정보 보호법」 제26조제8항), 회사는 이 제2부에 수탁 처리 내용을 공개합니다.
2. 이 개인정보의 처리 목적, 보유기간, 처리 근거는 각 고객사의 개인정보 처리방침에 따릅니다.
3. 회사는 고객사와의 위탁 계약과 고객사의 지시 범위, 그리고 법령상 안전성 확보조치(접속기록 작성·보관 등) 의무 범위 안에서만 이 개인정보를 처리하며, 위탁받은 업무 범위를 넘어 이용하거나 제3자에게 제공하지 않습니다(같은 법 제26조제5항).

<a id="b2"></a>
## 제20조 고객사를 위하여 처리하는 개인정보의 범주

고객사가 사용 설정한 기능과 입력한 내용에 따라 아래 항목의 일부만 처리합니다.

| 정보주체 | 범주 | 항목 |
|---|---|---|
| 임직원 | 기본 인사 정보 | 성명, 사번, 입사일·퇴사일·재직 상태, 직위·직급·직무, 소속, 생년월일, 신분증명 종류(번호는 저장하지 않음), 업무용 이메일, 근무지, 휴대전화번호 |
| 임직원 | 인적사항 | 한자 성명, 영문 성명, 국적, 개인 이메일, 그룹 입사일, 사진 |
| 임직원 | 근로자 명부 항목 | 성별, 주소, 퇴직 사유, 경력(이전 근무처, 근무 기간, 담당 업무, 직위, 퇴직 사유), 비고 |
| 임직원 | 근로계약 | 계약 기간과 종류, 임금액, 임금 지급 단위, 주 소정근로시간 |
