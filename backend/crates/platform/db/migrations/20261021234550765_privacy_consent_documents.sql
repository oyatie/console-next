<a id="a13"></a>
## 제13조 개인정보 자동 수집 장치의 설치·운영 및 거부

1. **쿠키:** 회사가 직접 설정하는 쿠키는 로그인 상태를 유지하기 위한 다음 하나입니다. 통신을 전달하는 Cloudflare가 설정하는 쿠키는 4호를 보십시오.

| 쿠키 이름 | 목적 | 저장 내용 | 보관 기간 | 특성 |
|---|---|---|---|---|
| `console_refresh` | 로그인 유지 | 로그인 갱신 토큰 | 최대 30일 | 자바스크립트로 읽을 수 없음(HttpOnly), 다른 사이트에서 보내는 요청에는 전송되지 않음(SameSite=Strict), 로그인 관련 주소(`/api/v1/auth`)에만 전송, 암호화 연결에서만 전송(Secure) |

2. **브라우저 저장소:** 서비스는 다음 값을 이용자 브라우저에 저장합니다. 언어 설정은 서버가 안내 문구의 언어를 정할 수 있도록 요청과 함께 전송되고, 작성 중인 입력 내용은 이용자가 저장하거나 제출할 때 서버로 전송됩니다. 그 밖의 값은 브라우저에만 남습니다.
   - 계속 남는 값(localStorage): 화면 테마, 언어, 마지막 활동 시각(자동 로그아웃용), 직원 목록의 표시 열 설정.
   - 탭을 닫으면 지워지는 값(sessionStorage): 작성 중인 입력 내용의 임시 저장본.
3. **분석·광고 도구:** 회사는 이용 행태 분석이나 광고를 위한 쿠키나 도구를 사용하지 않습니다.
4. **Cloudflare 보안 쿠키:** 통신을 전달하는 Cloudflare가 자동 접속 차단 등 보안 목적으로 쿠키를 설정할 수 있습니다. 【확인 필요: 실제로 설정되는 Cloudflare 쿠키 이름과 기간】
5. **거부 방법:** 브라우저 설정에서 쿠키 저장을 거부하거나 삭제할 수 있습니다.
   - Chrome: 설정 > 개인정보 보호 및 보안 > 서드 파티 쿠키 / 인터넷 사용 기록 삭제
   - Edge: 설정 > 쿠키 및 사이트 권한 > 쿠키 및 사이트 데이터 관리 및 삭제
   - Safari: 설정 > 개인정보 보호 > 웹사이트 데이터 관리

   【확인 필요: 브라우저 메뉴 이름은 제조사 화면 기준이며 미검증(UNVERIFIED)입니다. 게시 전에 각 브라우저 최신 버전에서 확인합니다.】

   `console_refresh` 쿠키를 거부하면 로그인 상태가 유지되지 않습니다.

