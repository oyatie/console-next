#[test]
fn amendments_are_applied() {
    let has = |d: ReasonDomain, c: &str| d.system_codes().iter().any(|s| s.code == c);
    assert!(has(ReasonDomain::ApprovalReturn, "NEEDS_SUPPLEMENT"));
    assert!(!has(ReasonDomain::OrgChangeReject, "NEEDS_SUPPLEMENT"));
    assert_eq!(ReasonDomain::ExitReject.system_codes().len(), 3);
    assert!(has(
        ReasonDomain::ExitReason,
        "ADVISED_RESIGNATION_BUSINESS"
    ));
    assert!(has(ReasonDomain::ExitReason, "ADVISED_RESIGNATION_FAULT"));
}

const ORG: ReasonDomain = ReasonDomain::OrgChangeReason;

fn tenant(code: &str, requires_note: bool, active: bool) -> TenantCode {
    TenantCode {
        code: code.to_owned(),
        requires_note,
        involuntary: false,
        notice_required: false,
        active,
    }
}

#[test]
fn a_system_code_passes_and_the_note_is_trimmed() {
    let ok = validate_reason(ORG, "RENAMING", Some("  rename  "), &[]).unwrap();
    assert_eq!(ok.code, "RENAMING");
    assert_eq!(ok.note.as_deref(), Some("rename"));
    let bare = validate_reason(ORG, "RENAMING", Some("   "), &[]).unwrap();
    assert_eq!(bare.note, None);
}

#[test]
fn an_unknown_code_or_a_code_of_another_domain_is_invalid() {
    for code in ["NOPE", "DUPLICATE_DRAFT", ""] {
        let err = validate_reason(ORG, code, None, &[]).unwrap_err();
        assert_eq!(
            (err.code(), err.field()),
            ("reason_code_invalid", "reason_code")
        );
    }
}

#[test]
fn other_needs_a_non_blank_note() {
    for note in [None, Some(""), Some(" \n ")] {
        let err = validate_reason(ORG, "OTHER", note, &[]).unwrap_err();
        assert_eq!(
            (err.code(), err.field()),
            ("reason_note_required", "reason_note")
        );
    }
    assert!(validate_reason(ORG, "OTHER", Some("x"), &[]).is_ok());
}

#[test]
fn the_note_is_capped_in_characters() {
    let at_cap = "é".repeat(NOTE_MAX_CHARS);
    assert!(validate_reason(ORG, "OTHER", Some(&at_cap), &[]).is_ok());
    let over = format!("{at_cap}x");
    let err = validate_reason(ORG, "OTHER", Some(&over), &[]).unwrap_err();
    assert_eq!(
        (err.code(), err.field()),
        ("reason_note_too_long", "reason_note")
    );
}

#[test]
fn tenant_codes_count_only_when_active_and_in_the_tenant_namespace() {
    let code = tenant_code(Uuid::from_u128(0xab));
    let rows = [tenant(&code, true, true)];
    let err = validate_reason(ORG, &code, None, &rows).unwrap_err();
    assert_eq!(err.code(), "reason_note_required");
    assert!(validate_reason(ORG, &code, Some("n"), &rows).is_ok());

    let inactive = [tenant(&code, false, false)];
    let err = validate_reason(ORG, &code, None, &inactive).unwrap_err();
    assert_eq!(err.code(), "reason_code_invalid");

    // A row outside the namespace (corrupt load) is not a code.
    let rogue = [tenant("ROGUE", false, true)];
    assert!(validate_reason(ORG, "ROGUE", None, &rogue).is_err());
}

#[test]
fn tenant_codes_have_the_checked_shape() {
    let code = tenant_code(Uuid::from_u128(u128::MAX));
    assert_eq!(code, format!("T_{}", "F".repeat(32)));
    assert!(is_tenant_code(&code) && is_well_formed(&code));
    assert!(!is_tenant_code("T_abc"));
    assert!(!is_tenant_code(&code.to_lowercase()));
    assert!(!is_well_formed("lower") && !is_well_formed("_X") && !is_well_formed(""));
    assert!(!is_well_formed(&"A".repeat(65)) && is_well_formed(&"A".repeat(64)));
}

#[test]
fn new_tenant_code_labels_are_trimmed_and_bounded() {
    let id = Uuid::from_u128(7);
    let ok = check_new_tenant_code(ORG, id, " Seoul site ", Some(" New site "), false).unwrap();
    assert_eq!(ok.code, tenant_code(id));
    assert_eq!(
        (ok.label_ko.as_str(), ok.label_en.as_deref()),
        ("Seoul site", Some("New site"))
    );
    assert_eq!(
        check_new_tenant_code(ORG, id, "x", None, true)
            .unwrap()
            .label_en,
        None
    );

    let blank = check_new_tenant_code(ORG, id, "  ", None, false).unwrap_err();
    assert_eq!(
        (blank.code(), blank.field()),
        ("reason_label_invalid", "label_ko")
    );
    let long = "a".repeat(LABEL_MAX_CHARS + 1);
    let err = check_new_tenant_code(ORG, id, "x", Some(&long), false).unwrap_err();
    assert_eq!(err.field(), "label_en");
}

