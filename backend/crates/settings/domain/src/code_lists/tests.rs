//! Roster invariants, validation, and the pin that keeps the BW-07
//! migration's generated `system_reason_codes()` equal to the roster. On a
//! pin failure, paste the printed block into the migration.

use super::*;
use console_kernel_core::{ErrorKind, KernelError};
use std::collections::HashSet;
use uuid::Uuid;

const MIGRATION: &str = include_str!("../../../../platform/db/migrations/0252_reason_codes.sql");
/// The latest migration that regenerates `system_reason_codes()` (settings_change, then import_rollback).
const GENERATED_IN: &str = include_str!(
    "../../../../platform/db/migrations/20261023090000000_registration_calendar_and_reasons.sql"
);
const BEGIN: &str = "-- BEGIN GENERATED by console-settings-domain code_lists/tests.rs";
const END: &str = "-- END GENERATED";

fn generated() -> String {
    let rows: Vec<String> = ReasonDomain::ALL
        .iter()
        .flat_map(|d| {
            d.system_codes().iter().enumerate().map(move |(i, c)| {
                format!(
                    "        ('{}', '{}', {}, {})",
                    d.as_str(),
                    c.code,
                    c.requires_note,
                    i + 1
                )
            })
        })
        .collect();
    format!(
        "{BEGIN}\nCREATE FUNCTION system_reason_codes()\nRETURNS TABLE (domain TEXT, code TEXT, requires_note BOOLEAN, sort INT)\nLANGUAGE sql IMMUTABLE PARALLEL SAFE\nAS $$\n    VALUES\n{}\n$$;\n{END}\n",
        rows.join(",\n")
    )
}

#[test]
fn migration_carries_the_generated_system_codes() {
    let expected = generated();
    assert!(
        GENERATED_IN.contains(&expected),
        "the latest system_reason_codes() migration is stale; replace its generated block with:\n{expected}"
    );
}

#[test]
fn migration_uses_the_same_code_predicates() {
    assert!(MIGRATION.contains("p_code ~ '^[A-Z][A-Z0-9_]{0,63}$'"));
    assert!(MIGRATION.contains("code ~ '^T_[0-9A-F]{32}$'"));
    assert!(MIGRATION.contains(&format!("char_length(comment) <= {NOTE_MAX_CHARS}")));
    assert!(MIGRATION.contains(&format!("char_length(label_ko) <= {LABEL_MAX_CHARS}")));
}

#[test]
fn every_domain_ends_in_other_and_only_other_needs_a_note() {
    for d in ReasonDomain::ALL {
        let codes = d.system_codes();
        assert_eq!(codes.last(), Some(&OTHER), "{}", d.as_str());
        for c in &codes[..codes.len() - 1] {
            assert!(!c.requires_note, "{}.{}", d.as_str(), c.code);
        }
    }
}

#[test]
fn system_codes_are_unique_well_formed_and_outside_the_tenant_namespace() {
    for d in ReasonDomain::ALL {
        let mut seen = HashSet::new();
        for c in d.system_codes() {
            assert!(seen.insert(c.code), "duplicate {}.{}", d.as_str(), c.code);
            assert!(is_well_formed(c.code), "{}", c.code);
            assert!(!c.code.starts_with(TENANT_CODE_PREFIX), "{}", c.code);
        }
    }
}

