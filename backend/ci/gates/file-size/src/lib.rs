//! File-size ratchet (EN-1).
//!
//! * A Rust file may carry at most [`CAP`] code lines ([`JOURNEY_CAP`] for a
//!   journey test under a `tests/` directory). See [`count::code_lines`].
//! * Files that were already over on adoption are pinned in [`BASELINE`] at
//!   their exact count. A pinned file may not grow, and when it shrinks the pin
//!   must come down in the same diff (a pin that only bounds from above lets a
//!   file shrink and grow back), so any drift either way fails.
//! * [`ratchet`] compares two baselines: CI runs it against the merge base so a
//!   regenerated baseline cannot raise a pin or the pinned total. A new pin is
//!   allowed only inside an unchanged-or-lower total: that is a move or split of
//!   pinned code (OD-3a), never new oversize code.

pub mod count;

use std::collections::BTreeMap;
use std::fmt;
use std::path::Path;

/// Code-line ceiling for every Rust file not otherwise capped.
pub const CAP: usize = 300;
/// Ceiling for `tests/**/*journey*.rs`: an end-to-end journey reads top to bottom.
pub const JOURNEY_CAP: usize = 500;
/// Directories walked, relative to the backend root.
pub const ROOTS: &[&str] = &["app", "crates", "ci", "test_support"];
/// The pinned oversize files, relative to the backend root.
pub const BASELINE: &str = "ci/gates/file-size/baseline.txt";
/// Generated files, never counted. Each needs its generator as the reason.
/// A `*` segment matches exactly one path segment (see [`exempt_matches`]).
pub const EXEMPT: &[(&str, &str)] = &[
    (
        "crates/contracts/src/gen_registry.rs",
        "generated by backend/openapi/split_openapi.py; edit the YAML fragments",
    ),
    (
        "crates/*/rest/src/openapi.rs",
        "generated per face by backend/openapi/split_openapi.py (write_openapi_rs); \
         INTEG's split + `git diff --exit-code` rejects a hand edit",
    ),
];

/// Path -> code lines, with `/` separators relative to the backend root.
pub type Counts = BTreeMap<String, usize>;

/// The ceiling that applies to `path`.
#[must_use]
pub fn cap(path: &str) -> usize {
    let mut parts = path.split('/');
    let name = parts.next_back().unwrap_or_default();
    if name.contains("journey") && parts.any(|dir| dir == "tests") {
        JOURNEY_CAP
    } else {
        CAP
    }
}

/// Counts every non-exempt `*.rs` under [`ROOTS`], skipping `target` and
/// hidden directories.
///
/// # Errors
/// Any directory or file that cannot be read.
pub fn measure(root: &Path) -> std::io::Result<Counts> {
    let mut counts = Counts::new();
    for dir in ROOTS {
        walk(root, &root.join(dir), &mut counts)?;
    }
    Ok(counts)
}

fn walk(root: &Path, dir: &Path, counts: &mut Counts) -> std::io::Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default();
        if path.is_dir() {
            if name != "target" && !name.starts_with('.') {
                walk(root, &path, counts)?;
            }
            continue;
        }
        if path.extension().is_none_or(|ext| ext != "rs") {
            continue;
        }
        let relative = path.strip_prefix(root).unwrap_or(&path);
        let key = relative.to_string_lossy().replace('\\', "/");
        if !EXEMPT
            .iter()
            .any(|(pattern, _)| exempt_matches(pattern, &key))
        {
            counts.insert(key, count::code_lines(&std::fs::read_to_string(&path)?));
        }
    }
    Ok(())
}

/// The baseline that `counts` implies: every file over its ceiling.
#[must_use]
pub fn oversize(counts: &Counts) -> Counts {
    counts
        .iter()
        .filter(|(path, lines)| **lines > cap(path))
        .map(|(path, lines)| (path.clone(), *lines))
        .collect()
}

/// Reads `path<TAB>lines` rows; `#` lines and blank lines are ignored.
///
/// # Errors
/// A malformed or duplicated row, by line number.
pub fn parse_baseline(text: &str) -> Result<Counts, String> {
    let mut pins = Counts::new();
    for (number, row) in text.lines().enumerate() {
        if row.trim().is_empty() || row.starts_with('#') {
            continue;
        }
        let parsed = row
            .split_once('\t')
            .and_then(|(path, lines)| Some((path, lines.parse::<usize>().ok()?)));
        let Some((path, lines)) = parsed else {
            return Err(format!(
                "{BASELINE}:{}: expected `path<TAB>lines`",
                number + 1
            ));
        };
        if pins.insert(path.to_owned(), lines).is_some() {
            return Err(format!(
                "{BASELINE}:{}: duplicate pin for {path}",
                number + 1
            ));
        }
    }
    Ok(pins)
}

/// Renders a baseline file, sorted so concurrent edits merge line by line.
#[must_use]
pub fn render_baseline(pins: &Counts) -> String {
    let mut out = String::from(
        "# Oversize Rust files, pinned at their code-line count (see ci/gates/file-size).\n\
         # Shrink-only: regenerate with `cargo run -p console-gate-file-size -- --write-baseline`.\n",
    );
    for (path, lines) in pins {
        out.push_str(&format!("{path}\t{lines}\n"));
    }
    out
}

/// One reason the gate fails.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Finding {
    /// An unpinned file is over its ceiling.
    OverCap {
        path: String,
        lines: usize,
        cap: usize,
    },
    /// A pinned file grew past its pin.
    Grew {
        path: String,
        lines: usize,
        pinned: usize,
    },
    /// A pinned file shrank, went under its ceiling or was deleted (`lines` 0):
    /// the pin must come down in the same diff.
    Stale {
        path: String,
        lines: usize,
        pinned: usize,
    },
    /// The new baseline pins more lines in total than the old one.
    TotalGrew { was: usize, now: usize },
    /// The new baseline raises a pin.
    Raised {
        path: String,
        was: usize,
        now: usize,
    },
    /// An [`EXEMPT`] entry matches no file.
    ExemptMissing { path: String },
}

impl fmt::Display for Finding {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::OverCap { path, lines, cap } => write!(
                f,
                "{path}: {lines} code lines, ceiling {cap}. Split the file; pins are only for files over on adoption."
            ),
            Self::Grew {
                path,
                lines,
                pinned,
            } => write!(
                f,
                "{path}: {lines} code lines, pinned at {pinned}. A pinned file may not grow; put new code in a new file."
            ),
            Self::Stale {
                path,
                lines,
                pinned,
            } => write!(
                f,
                "{path}: {lines} code lines, pinned at {pinned}. Lower the pin: run --write-baseline and commit {BASELINE}."
            ),
            Self::TotalGrew { was, now } => write!(
                f,
                "{BASELINE}: pinned total {was} -> {now}. The baseline may only shrink; split the file instead."
            ),
            Self::Raised { path, was, now } => write!(
                f,
                "{path}: pin raised {was} -> {now}. The baseline may only shrink; split the file instead."
            ),
            Self::ExemptMissing { path } => {
                write!(
                    f,
                    "{path}: listed in EXEMPT but matches no file; delete the entry."
                )
            }
        }
    }
}

/// Every file over its ceiling must be pinned at exactly its count, and every
/// pin must name such a file.
#[must_use]
pub fn check(counts: &Counts, pins: &Counts) -> Vec<Finding> {
    let mut findings = Vec::new();
    for (path, &lines) in counts {
        let cap = cap(path);
        match pins.get(path) {
            None if lines > cap => findings.push(Finding::OverCap {
                path: path.clone(),
                lines,
                cap,
            }),
            Some(&pinned) if lines > pinned => {
                findings.push(Finding::Grew {
                    path: path.clone(),
                    lines,
                    pinned,
                });
            }
            Some(&pinned) if lines < pinned || lines <= cap => {
                findings.push(Finding::Stale {
                    path: path.clone(),
                    lines,
                    pinned,
                });
            }
            _ => {}
        }
    }
    for (path, &pinned) in pins {
        if !counts.contains_key(path) {
            findings.push(Finding::Stale {
                path: path.clone(),
                lines: 0,
                pinned,
            });
        }
    }
    findings
}

/// Whether `path` matches the [`EXEMPT`] `pattern`, segment by segment.
#[must_use]
pub fn exempt_matches(pattern: &str, path: &str) -> bool {
    let (mut want, mut have) = (pattern.split('/'), path.split('/'));
    loop {
        match (want.next(), have.next()) {
            (None, None) => return true,
            (Some(w), Some(h)) if w == "*" || w == h => {}
            _ => return false,
        }
    }
}

/// Whether some file under `dir` matches `pattern` (`*` only in directory segments).
fn any_file_matches(dir: &Path, pattern: &str) -> bool {
    match pattern.split_once('/') {
        None => dir.join(pattern).is_file(),
        Some(("*", rest)) => std::fs::read_dir(dir)
            .into_iter()
            .flatten()
            .flatten()
            .any(|entry| entry.path().is_dir() && any_file_matches(&entry.path(), rest)),
        Some((segment, rest)) => any_file_matches(&dir.join(segment), rest),
    }
}

/// [`EXEMPT`] entries that match no file.
#[must_use]
pub fn missing_exemptions(root: &Path) -> Vec<Finding> {
    EXEMPT
        .iter()
        .filter(|(path, _)| !any_file_matches(root, path))
        .map(|(path, _)| Finding::ExemptMissing {
            path: (*path).to_owned(),
        })
        .collect()
}

/// Pins of `new` raised over `old`, and a pinned total that grew.
#[must_use]
pub fn ratchet(old: &Counts, new: &Counts) -> Vec<Finding> {
    let mut findings: Vec<Finding> = new
        .iter()
        .filter_map(|(path, &now)| {
            let was = *old.get(path)?;
            (now > was).then(|| Finding::Raised {
                path: path.clone(),
                was,
                now,
            })
        })
        .collect();
    let (was, now) = (old.values().sum(), new.values().sum());
    if now > was {
        findings.push(Finding::TotalGrew { was, now });
    }
    findings
}
