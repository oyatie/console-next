import { expect, test } from "@playwright/test";
import { expectAccessible } from "./a11y";
import { apiOf, bearerOf } from "./helpers/api";
import { cellOf, officeSchedule, openMonth, pastWorkDay } from "./helpers/attendance-records";
import { chooseRadio, kstDate, registerEmployee } from "./flows";
import { staffedTenant } from "./setup-flows";

test("long records require per-cell confirmation, save evidence only, and confirm corrections", { tag: "@hr" }, async ({ browser }) => {
  test.setTimeout(600_000);
  const { admin } = await staffedTenant(browser, "attlong", "긴기록주식회사");
  const bearer = bearerOf(admin);
  await registerEmployee(admin, { name: "윤하준", number: "L-0001", hired: kstDate(-60) });
  await officeSchedule(admin);
  const api = apiOf(admin, bearer);
  const people = (await (await api("/employees?limit=10")).json()) as { items: { id: string; name: string }[] };
  const person = people.items.find((p) => p.name === "윤하준")!.id;
  const { month, date } = await pastWorkDay(api, person);
  const history = async () => (await (await api(`/attendance/people/${person}/month?month=${month}`)).json()) as { history: unknown[]; days: { date: string; recognition: { recorded: number; recognised: number; approved: number } }[] };
  const refused = await api("/attendance/entries", "POST", { cells: [{ employee_id: person, work_date: date, value: "5-23" }], source: "MANUAL", evidence: { kind: "PAPER_SHEET" } }, { "Idempotency-Key": `long-${crypto.randomUUID()}` });
  expect(refused.status()).toBe(422);
  expect((await refused.json()).error.details.refused[0]).toMatchObject({ code: "span_too_long", long_span_minutes: 960 });
  expect((await history()).history).toHaveLength(0);
  const grid = await openMonth(admin, month);
  await cellOf(admin, "윤하준", date).click();
  await admin.keyboard.type("5-23");
  await admin.keyboard.press("Enter");
  await grid.focus();
  await admin.keyboard.press("ControlOrMeta+s");
  const save = admin.getByRole("complementary", { name: /저장 · 초안 1칸/ });
  const confirm = save.getByRole("checkbox", { name: /5-23.*확인 기준 960분/ });
  await expect(confirm).not.toBeChecked();
  await chooseRadio(save, /출근부 \(종이\)/);
  await expect(save.getByRole("button", { name: /칸 저장/ })).toHaveAttribute("aria-disabled", "true");
  expect((await history()).history).toHaveLength(0);
  await expectAccessible(admin, "long record confirmation");
  await confirm.press("Space");
  await expect(confirm).toBeChecked();
  await expect(save.getByRole("button", { name: "1칸 저장", exact: true })).toBeEnabled();
  await save.getByRole("button", { name: "1칸 저장", exact: true }).click();
  await expect(admin.getByRole("status").filter({ hasText: "1칸을 저장했습니다" })).toBeVisible();
  const written = await history();
  expect(written.history).toHaveLength(1);
  expect(written.days.find((d) => d.date === date)!.recognition).toMatchObject({ recorded: 1080, recognised: 1020, approved: 0 });

  await cellOf(admin, "윤하준", date).click();
  await admin.keyboard.press("p");
  await admin.getByRole("button", { name: "정정", exact: true }).click();
  const correction = admin.getByRole("complementary", { name: /기록 정정/ });
  await correction.getByRole("textbox", { name: /정정할 값/ }).fill("4-23");
  await correction.getByRole("textbox", { name: /사유/ }).fill("원본과 대조");
  await chooseRadio(correction, /출근부 \(종이\)/);
  const corrected = correction.getByRole("checkbox", { name: /4-23.*확인 기준 960분/ });
  await expect(corrected).not.toBeChecked();
  expect((await history()).history).toHaveLength(1);
  await corrected.press("Space");
  await expect(corrected).toBeChecked();
  await correction.getByRole("textbox", { name: /정정할 값/ }).fill("3-23");
  await expect(correction.getByRole("checkbox", { name: /3-23/ })).not.toBeChecked();
  await correction.getByRole("checkbox", { name: /3-23/ }).press("Space");
  await correction.getByRole("button", { name: /정정.*저장|정정 기록/ }).click();
  await expect.poll(async () => (await history()).history.length).toBe(2);
  expect((await history()).days.find((d) => d.date === date)!.recognition.approved).toBe(0);
  await admin.context().close();
});
