import { expect, test } from "@playwright/test";
import { addDays } from "../apps/web/src/ui/date/days";
import { go, kstDate, registerEmployee } from "./flows";
import { staffedTenant } from "./setup-flows";
import { apiOf, bearerOf, codeOf } from "./helpers/api";
import { fillDate, signOff } from "./sheet";
import { hrAct, openHistory } from "./record";
import { atPhoneWidth, expectAccessible, fits } from "./a11y";
import { expectStable, forgetResize } from "./stability";

const acks = { privacy_notice_ack: true, korean_labor_law_ack: true, payroll_cutoff_ack: true, retirement_settlement_ack: true };

test("legal rules appear before submit: protected dismissal, notice pay, renewal, former record and rehire", { tag: ["@hr", "@negative", "@regression"] }, async ({ browser }) => {
  test.setTimeout(300_000);
  const { admin } = await staffedTenant(browser, "legal", "법무검토상사");
  await admin.setViewportSize({ width: 1440, height: 1000 });
  await forgetResize(admin);
  const api = apiOf(admin, bearerOf(admin));
  await registerEmployee(admin, { name: "보호직원", number: "LEGAL-A", hired: kstDate(-400), unit: "본사" });
  const protectedId = new URL(admin.url()).pathname.split("/").pop()!;
  const leave = await api(`/employees/${protectedId}/lifecycle-events`, "POST", { event_type: "LEAVE_OF_ABSENCE", effective_date: kstDate(0), expected_return_date: kstDate(40), leave_type: "CHILDCARE", comment: "합성 육아휴직", signoffs: acks }, { "Idempotency-Key": crypto.randomUUID() });
  expect(leave.ok()).toBe(true);
  await go(admin, `/people/${protectedId}`);
  await admin.getByRole("button", { name: "퇴직 보고", exact: true }).click();
  let sheet = admin.getByRole("dialog");
  await fillDate(sheet, kstDate(0), "마지막 근무일");
  await sheet.getByRole("radiogroup", { name: /^퇴직 사유 · 비자발적 퇴직/ }).getByText("징계해고", { exact: true }).click();
  const protection = sheet.getByRole("note", { name: "해고 보호기간" });
  await expect(protection).toContainText("제19조제3항");
  await expect(sheet).toContainText("해고 보호기간에는 해고할 수 없습니다");
  await expectStable(admin, "protected dismissal preflight leaves report fields in place");
  await sheet.getByRole("textbox", { name: /^퇴직 경위/ }).fill("합성 보고");
  await sheet.getByRole("button", { name: /^퇴직 보고 1명 반영/ }).click();
  await expect(sheet.getByRole("alert")).toContainText("exit_protected_period");
  await expectAccessible(admin, "protected dismissal preflight and refusal");
  await atPhoneWidth(admin, async () => { await fits(admin, "protected dismissal"); await expectAccessible(admin, "protected dismissal at phone width"); });
  await admin.keyboard.press("Escape");

  await registerEmployee(admin, { name: "예고직원", number: "LEGAL-B", hired: kstDate(-400), unit: "본사" });
  const exitedId = new URL(admin.url()).pathname.split("/").pop()!;
  const beforeExit = await (await api(`/employees/${exitedId}`)).json();
  const reported = await api("/hr/exit-cases", "POST", { employee_id: exitedId, effective_exit_date: kstDate(-1), site_manager_note: "합성 해고", exit_reason_code: "DISCIPLINARY_DISMISSAL" }, { "Idempotency-Key": crypto.randomUUID() });
  expect(reported.status()).toBe(201);
  const exitCase = await reported.json();
  const notice = { reason_text: "합성 서면 사유", served_on: addDays(exitCase.effective_exit_date, -14), method: "CERTIFIED_MAIL", evidence_ref: "synthetic-receipt" };
  const short = await api(`/hr/exit-cases/${exitCase.id}/confirm`, "POST", { dismissal_notice: notice, signoffs: acks });
  expect([short.status(), await codeOf(short)]).toEqual([409, "dismissal_notice_short"]);
  await go(admin, `/people/${exitedId}`);
  await admin.reload();
  await admin.getByRole("button", { name: "인사 확인하고 퇴직 처리", exact: true }).click();
  sheet = admin.getByRole("dialog");
  const written = sheet.getByRole("group", { name: "해고 서면 통지 (근로기준법 제27조)" });
  await written.getByRole("textbox", { name: /^해고사유/ }).fill(notice.reason_text);
  const preflight = admin.waitForResponse((response) => response.url().includes(`/employees/${exitedId}/exit-guards?`) && response.url().includes(notice.served_on));
  await fillDate(written, notice.served_on, "통지일");
  const { notice_pay: pay } = await (await preflight).json();
  expect(typeof pay.required_days).toBe("number");
  await written.getByRole("radiogroup", { name: /^전달 방법/ }).getByText("내용증명", { exact: true }).click();
  await written.getByRole("textbox", { name: /^증빙 참조/ }).fill(notice.evidence_ref);
  await expect(written).toContainText("해고예고수당 지급 대상");
  await expectStable(admin, "notice preflight leaves confirmation fields in place");
  await fillDate(written, addDays(exitCase.effective_exit_date, -pay.required_days), "통지일");
  await expect(written.getByRole("radiogroup", { name: /^해고예고 부족 시 조치/ })).toHaveCount(0);
  await expectStable(admin, "sufficient notice keeps the confirmation memo in place");
  await fillDate(written, notice.served_on, "통지일");
  await expect(written).toContainText("해고예고수당 지급 대상");
  await expectStable(admin, "short notice restores the disposition without moving later fields");
  await signOff(sheet.getByRole("group", { name: "확인 사항" }));
  const confirm = sheet.getByRole("button", { name: /^퇴직 1명 반영/ });
  await expect(confirm).toHaveAttribute("aria-disabled", "true");
  await written.getByRole("radiogroup", { name: /^해고예고 부족 시 조치/ }).getByText("해고예고수당 지급", { exact: true }).click();
  await expectAccessible(admin, "notice pay disposition before confirmation");
  await atPhoneWidth(admin, async () => { await fits(admin, "notice pay disposition"); await expectAccessible(admin, "notice pay disposition at phone width"); });
  await confirm.click();
  await expect(sheet).toBeHidden();
  const head = admin.locator("header").filter({ has: admin.getByRole("heading", { name: "예고직원", exact: true }) });
  await expect(head).toContainText("보존 기한");
  await expect(admin.getByRole("heading", { name: "고용 기록", exact: true })).toBeVisible();
  await expect(admin.getByRole("main")).not.toContainText("열람 권한 없음");
  await expect(admin.getByRole("button", { name: "고용 기록 수정", exact: true })).toHaveCount(0);
  await expect(head.getByRole("button", { name: /^(퇴직|등록 취소)$/ })).toHaveCount(0);
  const tops = await head.getByRole("group", { name: "인사카드 동작", exact: true }).getByRole("button").evaluateAll((buttons) => buttons.map((b) => Math.round(b.getBoundingClientRect().top)));
  expect(new Set(tops).size, "former employee actions stay on one row at desktop width").toBe(1);
  await expect(admin.locator("#s1").getByRole("button", { name: /수정|추가/ })).toHaveCount(0);
  const directWrite = await api(`/employees/${exitedId}/employment-facts`, "PATCH", [{ op: "test", path: "/work_email", value: null }, { op: "replace", path: "/work_email", value: "synthetic@example.invalid" }]);
  expect([directWrite.status(), await codeOf(directWrite)]).toEqual([409, "employee_exited_read_only"]);
  const retained = await (await api(`/employees/${exitedId}`)).json();
  expect(retained.retention.rule.code).toBe("EMPLOYMENT_RECORD_RETENTION_YEARS");
  await expectAccessible(admin, "former employee retention band");
  await atPhoneWidth(admin, async () => { await fits(admin, "former employee record"); await expectAccessible(admin, "former employee record at phone width"); });
  await admin.getByRole("button", { name: "재입사로 등록", exact: true }).click();
  await expect(admin.getByRole("status").filter({ hasText: "이전 퇴직 결정" })).toBeVisible();
  await expectAccessible(admin, "rehire waits for the prior exit decision");
  await atPhoneWidth(admin, async () => { await fits(admin, "rehire refusal"); await expectAccessible(admin, "rehire refusal at phone width"); });
  const earlyRehire = await api(`/employees/${exitedId}/rehire`, "POST", { hire_date: kstDate(1), employment_type: "REGULAR", org_unit_id: beforeExit.employee.org_unit_id, position: "사원", idempotency_key: crypto.randomUUID() });
  expect([earlyRehire.status(), await codeOf(earlyRehire)]).toEqual([409, "rehire_exit_case_open"]);
  await go(admin, `/people/exits/${exitCase.id}`);
  await expect(admin.getByRole("main")).toContainText("해고예고수당 지급 대상");

  await registerEmployee(admin, { name: "갱신직원", number: "LEGAL-C", hired: kstDate(-301), contractEnd: kstDate(40), unit: "본사" });
  const renewalId = new URL(admin.url()).pathname.split("/").pop()!;
  await admin.reload();
  await openHistory(admin);
  await hrAct(admin, "계약 갱신");
  sheet = admin.getByRole("dialog");
  const periods = sheet.getByRole("group", { name: "계약 기간 빠른 선택" });
  const crossing = periods.getByRole("button").filter({ hasText: "2년" });
  await expect(crossing).toHaveAttribute("aria-disabled", "true");
  await expect(crossing).toContainText("한도");
  await expect(sheet.getByRole("button", { name: "무기계약 전환", exact: true })).toHaveCount(0);
  await fillDate(sheet, kstDate(900), "새 계약 종료일");
  await expect(sheet.getByRole("button", { name: "무기계약 전환", exact: true })).toBeVisible();
  await expect(sheet.getByRole("button", { name: "예외", exact: true })).toHaveCount(0);
  await expect(sheet.getByRole("textbox", { name: "승인된 예외 참조" })).toHaveCount(0);
  const crossingWrite = await api(`/employees/${renewalId}/lifecycle-events`, "POST", { event_type: "CONTRACT_RENEWAL", effective_date: kstDate(41), contract_end_date: kstDate(900), comment: "합성 갱신", signoffs: acks }, { "Idempotency-Key": crypto.randomUUID() });
  expect([crossingWrite.status(), await codeOf(crossingWrite)]).toEqual([409, "fixed_term_limit"]);
  await expectAccessible(admin, "renewal limit and alternatives");
  await atPhoneWidth(admin, async () => { await fits(admin, "renewal limit"); await expectAccessible(admin, "renewal alternatives at phone width"); });
  await sheet.getByRole("button", { name: "무기계약 전환", exact: true }).click();
  await expect(admin.getByRole("dialog")).toContainText("고용형태");
  await admin.keyboard.press("Escape");
  await hrAct(admin, "계약 갱신");
  sheet = admin.getByRole("dialog");
  await sheet.getByRole("button", { name: "갱신 안 함", exact: true }).click();
  sheet = admin.getByRole("dialog");
  await expect(sheet).toContainText("계약기간 만료");
  await sheet.getByRole("textbox", { name: /^퇴직 경위/ }).fill("계약을 갱신하지 않기로 결정했습니다");
  await sheet.getByRole("button", { name: /^퇴직 보고 1명 반영/ }).click();
  await expect(sheet).toBeHidden();
  const expiryCases = await (await api(`/hr/exit-cases?employee_id=${renewalId}`)).json();
  expect(expiryCases.items).toEqual(expect.arrayContaining([expect.objectContaining({ exit_reason_code: "CONTRACT_END", effective_exit_date: kstDate(40) })]));
});
