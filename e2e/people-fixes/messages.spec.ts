import { expect, test } from "@playwright/test";
import { expectAccessible } from "../a11y";
import { go, koDate, kstDate, option } from "../flows";
import { apiOf, bearerOf, codeOf } from "../helpers/api";
import { peopleWorld, registerAt } from "../helpers/people-fixes";
import { fillDate, signOff } from "../sheet";

async function contractForm(page: import("@playwright/test").Page, start: string, end: string) {
  const region = page.getByRole("region", { name: "근로계약" });
  await region.getByRole("button", { name: "계약 기록", exact: true }).click();
  const form = region.getByRole("form", { name: "계약 기록" });
  await form.getByLabel(/^계약 종류/).selectOption({ label: "기간제 근로계약" });
  await fillDate(form, start, "계약 시작일");
  await fillDate(form, end, "계약 종료일");
  await form.getByRole("textbox", { name: /^임금/ }).fill("3000000");
  await option(page, "임금 단위", "월급").click();
  await form.getByLabel(/^주 소정근로시간/).fill("40");
  return form;
}

test("solo: a contract overlap names its period and opens that contract's correction; a rehire refusal explains the prior exit", { tag: ["@hr", "@regression", "@negative"] }, async ({ browser }) => {
  test.setTimeout(300_000);
  const { admin } = await peopleWorld(browser, "peoplemessages");
  const api = apiOf(admin, bearerOf(admin));
  const worker = await registerAt(admin, "사람기술", "계약인", "PE-0001");
  const first = await contractForm(admin, kstDate(-100), kstDate(100));
  await first.getByRole("button", { name: "계약 기록", exact: true }).click();
  await expect(first).toBeHidden();
  const contracts = async () => (await (await api(`/employees/${worker.id}/contracts`)).json()) as object;
  const contractsBefore = await contracts();
  const overlapping = await contractForm(admin, kstDate(-50), kstDate(200));
  const refused = admin.waitForResponse((r) => r.request().method() === "POST" && r.url().endsWith(`/employees/${worker.id}/contracts`));
  await overlapping.getByRole("button", { name: "계약 기록", exact: true }).click();
  expect((await refused).status()).toBe(409);
  expect(await codeOf(await refused)).toBe("contract_overlap");
  await expect(overlapping.getByRole("alert")).toContainText("기간제 근로계약");
  await expect(overlapping.getByRole("alert")).toContainText("기간이 겹칩니다");
  expect(await contracts()).toEqual(contractsBefore);
  await expectAccessible(admin, "people: overlap names the existing contract");
  await overlapping.getByRole("button", { name: /계약 정정$/ }).click();
  const correction = admin.getByRole("form", { name: /^계약 정정/ });
  await expect(correction.getByLabel(/^계약 시작일/)).toHaveValue(koDate(kstDate(-100)));
  await correction.getByRole("textbox", { name: /^임금/ }).fill("3100000");
  await correction.getByRole("button", { name: "정정 기록" }).click();
  await expect(correction).toBeHidden();

  await admin.getByRole("button", { name: "퇴직 보고", exact: true }).click();
  const report = admin.getByRole("dialog", { name: /퇴직 보고/ });
  await fillDate(report, kstDate(-2), "마지막 근무일");
  await report.getByRole("textbox", { name: /^퇴직 경위/ }).fill("개인 사정");
  await report.getByRole("radiogroup", { name: /^퇴직 사유/ }).getByText("개인 사정", { exact: true }).click();
  await report.getByRole("button", { name: "퇴직 보고 1명 적용" }).click();
  await admin.getByRole("button", { name: "인사 확인하고 퇴직 처리" }).click();
  await signOff(admin.getByRole("dialog").getByRole("group", { name: "확인 사항" }));
  await admin.getByRole("dialog").getByRole("button", { name: /퇴직 1명 (적용|예약)/ }).click();
  await expect(admin.getByRole("dialog")).toBeHidden();
  const read = async () => ((await (await api(`/employees/${worker.id}`)).json()) as { employee: { status: string; exit_date: string } }).employee;
  await expect.poll(async () => (await read()).status).toBe("EXITED");
  const caseHref = await admin.getByRole("link", { name: "퇴직 건 열기", exact: true }).getAttribute("href");
  await go(admin, caseHref!);
  await admin.getByRole("region", { name: /지금/ }).getByRole("button", { name: "퇴직 본사 확인 1명 적용", exact: true }).click();
  await expect(admin.getByRole("main")).toContainText("본사 확인됨");
  const before = await read();
  await go(admin, `/people/${worker.id}?act=rehire`);
  const rehire = admin.getByRole("dialog", { name: "재입사로 등록" });
  await rehire.getByRole("radiogroup", { name: /^어디에 둡니까/ }).getByText("사업장 직속 · 부서 없이", { exact: true }).click();
  await rehire.getByRole("combobox", { name: "둘 곳" }).fill("본사");
  await admin.getByRole("option", { name: /사람기술.*본사/ }).click();
  await fillDate(rehire, kstDate(), "입사일");
  await rehire.getByRole("radiogroup", { name: /^고용형태/ }).getByText("정규직", { exact: true }).click();
  await signOff(rehire);
  const url = `**/api/v1/employees/${worker.id}/rehire`;
  await admin.route(url, (route) => route.continue({ postData: JSON.stringify({ ...route.request().postDataJSON(), hire_date: before.exit_date }) }));
  const early = admin.waitForResponse((r) => r.request().method() === "POST" && r.url().endsWith(`/employees/${worker.id}/rehire`));
  await rehire.getByRole("button", { name: /재입사 1명 (예약|적용)/ }).click();
  expect((await early).status()).toBe(422);
  expect(await codeOf(await early)).toBe("rehire_date_not_after_exit");
  await expect(rehire.getByRole("alert")).toContainText(`재입사일은 퇴직일 ${koDate(kstDate(-1))}부터 선택할 수 있습니다.`);
  expect(await read()).toEqual(before);
  await admin.unroute(url);
  await rehire.getByRole("button", { name: /재입사 1명 (예약|적용)/ }).click();
  await expect(rehire).toBeHidden();
  expect((await read()).status).toBe("ACTIVE");
});
