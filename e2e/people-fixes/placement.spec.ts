import { expect, test } from "@playwright/test";
import { expectAccessible } from "../a11y";
import { go, kstDate } from "../flows";
import { apiOf, bearerOf } from "../helpers/api";
import { peopleWorld, pickBulk, registerAt } from "../helpers/people-fixes";
import { hrAct } from "../record";
import { fillDate, reasonBox, sheet, todayPreset } from "../sheet";

test("solo: identically named workplaces keep their entity IDs; typed warnings survive receipts and reloads", { tag: ["@hr", "@regression"] }, async ({ browser }) => {
  test.setTimeout(300_000);
  const { admin, first, second } = await peopleWorld(browser, "peopleplacement");
  const api = apiOf(admin, bearerOf(admin));
  const a = await registerAt(admin, "사람정밀", "경고인", "PF-0001", "1");
  expect(a.receipt).toContain("최저임금 미달");
  await expect(admin.getByRole("status").filter({ hasText: "최저임금 미달" })).toBeVisible();
  await admin.reload();
  await expect(admin.getByRole("status").filter({ hasText: "최저임금 미달" })).toContainText("급여와 계약의 근무시간");
  const b = await registerAt(admin, "사람기술", "경고인", "PF-0002", "1", "010-1234-0025");
  expect(b.receipt).toContain("이름과 입사일이 같은 직원");
  expect(b.receipt).toContain("최저임금 미달");
  const detail = async (id: string) => (await (await api(`/employees/${id}`)).json()) as { employee: { legal_entity_id: string; workplace_id: string }; warnings: { code: string }[] };
  expect((await detail(a.id)).employee.legal_entity_id).toBe(first);
  const before = await detail(b.id);
  expect(before.employee.legal_entity_id).toBe(second);
  expect(before.warnings.map((w) => w.code)).toEqual(expect.arrayContaining(["same_name_same_hire_date", "pay_below_minimum_wage"]));
  await expectAccessible(admin, "people: two typed notices on the card");

  await hrAct(admin, "전보");
  const move = sheet(admin, "경고인 전보");
  await move.getByRole("combobox", { name: "어디로" }).fill("본사");
  await expect(admin.getByRole("option", { name: /사람정밀.*본사/ })).toHaveCount(0);
  await move.getByRole("combobox", { name: "어디로" }).fill("분원");
  await admin.getByRole("option", { name: /분원/ }).click();
  await fillDate(move, kstDate(-1));
  await move.getByRole("radiogroup", { name: /^사유 분류/ }).getByRole("radio").first().locator("xpath=ancestor::label[1]").click();
  await reasonBox(move).fill("같은 법인 사업장 전근");
  await move.getByRole("button", { name: /전보 \(지난 날짜\)$/ }).click();
  await expect(move).toBeHidden();
  expect((await detail(b.id)).employee.legal_entity_id).toBe(second);

  await pickBulk(admin, "PF-0002");
  await admin.getByRole("group", { name: "무엇을" }).getByRole("button", { name: "전보" }).click();
  const where = admin.getByRole("listbox", { name: "어디로" });
  await expect(where).not.toContainText("첫법인인사팀");
  await where.getByRole("option", { name: /^본사/ }).click();
  await todayPreset(admin).click();
  await admin.getByRole("radiogroup", { name: /^사유/ }).getByRole("radio").first().locator("xpath=ancestor::label[1]").click();
  await admin.getByRole("textbox", { name: /^메모/ }).fill("본사로 복귀");
  await admin.getByRole("button", { name: /^1명 전보 · 오늘 반영/ }).click();
  await expect(admin.getByRole("status").filter({ hasText: /1명 전보/ }).first()).toBeVisible();
  expect((await detail(b.id)).employee).toMatchObject({ legal_entity_id: before.employee.legal_entity_id, workplace_id: before.employee.workplace_id });
  await go(admin, `/people/${b.id}`);
  await expectAccessible(admin, "people: bulk transfer returns to the same entity's headquarters");
  const main = admin.getByRole("main");
  await admin.getByRole("button", { name: "로그아웃", exact: true }).focus();
  await admin.keyboard.press("Tab");
  await expect(main).toBeFocused();
  await expect(main).toHaveAccessibleName("본문");
  await expect(main).toHaveCSS("outline-style", "solid");
  await main.press("Home");
  await expect.poll(() => main.evaluate((el) => el.scrollTop)).toBe(0);
  await main.press("PageDown");
  await expect.poll(() => main.evaluate((el) => el.scrollTop)).toBeGreaterThan(0);
});
