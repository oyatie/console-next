import { expect, test } from "@playwright/test";
import { firstSignIn, go, routeReady } from "./flows";
import { apiOf, bearerOf } from "./helpers/api";
import { setupCompany, startOperations } from "./setup-flows";
import { inviteAccount } from "./access-flows";
import { openTenant } from "./helpers/tenant";
import { revealUnit } from "./structure-flows";

for (const routeFirst of [false, true]) test(`an invited approver opens a routed change from the work inbox (routing first: ${routeFirst})`, { tag: ["@org", "@live"] }, async ({ browser }, info) => {
  test.setTimeout(300_000);
  const admin = await openTenant(browser, `approvaldelivery${routeFirst ? "routed" : "prepared"}`, "결재전달회사");
  await setupCompany(admin, "결재전달회사", "본점");
  const token = bearerOf(admin);
  await startOperations(admin);
  await admin.reload();
  await expect.poll(token).not.toBe("");
  const api = apiOf(admin, token);
  // The routing settings screen has its own journey; use the real settings command here.
  const earlyCode = routeFirst ? undefined : await inviteAccount(admin, "이임원", "oversight");
  const policy = await api("/settings/approval.policy.org_structure", "POST", { value: "route", reason_code: "POLICY_REVIEW" });
  expect(policy.status(), await policy.text()).toBe(201);
  const code = earlyCode ?? await inviteAccount(admin, "이임원", "oversight");
  await admin.reload();
  await go(admin, "/org");
  await revealUnit(admin, "본점");
  await expect.poll(() => new URL(admin.url()).searchParams.get("sel")).toBeTruthy();
  await go(admin, `/org?sel=${new URL(admin.url()).searchParams.get("sel")}&act=dept-add`);
  const card = admin.getByRole("dialog", { name: "부서 신설", exact: true });
  await card.getByLabel("부서 이름").fill("결재전달부");
  await card.getByRole("button", { name: /^오늘/ }).click();
  await card.getByLabel("사유").fill("결재 전달 확인");
  const submitted = admin.waitForResponse(r => r.request().method() === "POST" && /\/org-changes\/[^/]+\/submit$/.test(new URL(r.url()).pathname));
  await card.getByRole("button", { name: /결재 요청$/ }).click();
  const change = await (await submitted).json();
  expect(change.status).toBe("IN_APPROVAL");
  const exec = await firstSignIn(browser, code);
  const approverToken = bearerOf(exec);
  await exec.reload();
  await expect.poll(approverToken).not.toBe("");
  const approverApi = apiOf(exec, approverToken);
  const queue = await approverApi("/approvals?box=pending");
  await info.attach("approval-list", { body: await queue.body(), contentType: "application/json" });
  await exec.getByRole("region", { name: "업무함", exact: true }).getByRole("link", { name: "업무함에서 모두 보기", exact: true }).click();
  await expect(exec).toHaveURL(/\/inbox$/);
  await routeReady(exec, "/inbox");
  await exec.screenshot({ path: info.outputPath("inbox-after.png"), fullPage: true });
  await info.attach("inbox", { body: await exec.getByRole("main").ariaSnapshot(), contentType: "text/plain" });
  const inbox = exec.getByRole("region", { name: "업무함", exact: true });
  await expect(inbox).toContainText("결재전달부");
  await expect(exec.getByRole("navigation", { name: "주 메뉴", exact: true }).getByRole("link", { name: "결재함", exact: true })).toBeVisible();
  await inbox.getByRole("row", { name: /결재전달부/ }).getByRole("link", { name: "변경 내용 검토", exact: true }).click();
  await expect(exec).toHaveURL(new RegExp(`/org/changes/${change.id}$`));
  await routeReady(exec, `/org/changes/${change.id}`);
  await expect(exec.getByRole("heading", { name: /결재전달부/, level: 1 })).toBeVisible();
  const decision = await approverApi(`/org-changes/${change.id}/approval-steps/${change.approvalSteps[0].id}/decision`, "POST", { decision: "APPROVED" });
  expect(decision.status()).toBe(403);
  expect((await decision.json()).error.code).toBe("org_change.refuse.identity_unbound");
  await info.attach("decision-response", { body: await decision.body(), contentType: "application/json" });
});
