test("setup actions fit inside the inbox rail at 390px", { tag: ["@first-run", "@regression"] }, async ({ browser }) => {
  const admin = await soloTenant(browser, "inbox-rail-narrow", "설정화면그룹");
  await admin.setViewportSize({ width: 390, height: 844 });
  await admin.goto("/");
  const rail = setupRail(admin);
  const step = rail.locator("[data-step]").first();
  await expect(step).toBeVisible();
  await expect(step.getByRole("link")).toHaveCount(3);
  const bounds = await step.boundingBox();
  const title = await step.locator(":scope > span").first().boundingBox();
  expect(bounds).not.toBeNull();
  expect(title).not.toBeNull();
  for (const link of await step.getByRole("link").all()) {
    const action = await link.boundingBox();
    expect(action).not.toBeNull();
    expect(action!.y).toBeGreaterThanOrEqual(title!.y + title!.height);
    expect(action!.x).toBeGreaterThanOrEqual(bounds!.x);
    expect(action!.x + action!.width).toBeLessThanOrEqual(bounds!.x + bounds!.width);
  }
  await expectAccessible(admin, "setup rail inside the narrow inbox");
  await admin.context().close();
});

test("BL-013: solo rail, equal paths, J/K, 2,000 applied people and a prepared role", { tag: ["@first-run", "@hr"] }, async ({ browser }, info) => {
  test.setTimeout(300_000);
  const admin = await soloTenant(browser, "ideal-rail", "첫운영그룹");
  const read = apiAs(admin);
  await admin.reload();
  const rail = setupRail(admin);
  const steps = rail.locator("[data-step]");
  await expect(steps).toHaveCount(7);
  const checklist = await read<{ steps: { key: string }[] }>("/api/v1/onboarding/checklist");
  expect(checklist.steps.map((s) => s.key)).toEqual(["entity", "workplace", "org", "passkey", "employees", "roles", "golive"]);
  const entity = steps.first();
  expect(await entity.getByRole("link").evaluateAll((els) => els.map((el) => el.className))).toEqual(["btn", "btn", "btn"]);
  await entity.focus();
  await admin.keyboard.press("j");
  await expect(steps.nth(1)).toBeFocused();
  await admin.keyboard.press("k");
  await expect(entity).toBeFocused();
  await admin.keyboard.press("Enter");
  await expect(admin).toHaveURL(/\/org\/entities\/new$/);
  await go(admin, "/");
  await expectAccessible(admin, "ideal first-run empty rail");
  await probeActions(admin);
  await setupCompany(admin, "첫운영정밀", "본사");
  await go(admin, "/org");
  await addDepartments(admin, "본사", ["인사팀"]);
  const rows = many("FR", 2000, ["인사팀"]).map((r, i) => ({ ...r, name: `직원${String(i + 1).padStart(4, "0")}`, hired: kstDate(-30), unit: i < 1982 ? "인사팀" : "" }));
  await go(admin, "/people/import");
  await chooseWorkbook(admin, "2000명.xlsx", await workbook([plain("첫운영정밀", rows)]));
  await admin.getByRole("button", { name: "명부 미리보기" }).click();
  await admin.getByRole("button", { name: "모의 반영 실행" }).click();
  await expect(rowsGrid(admin)).toBeVisible({ timeout: 60_000 });
  await admin.getByRole("button", { name: "명부 반영: 신규 2,000명 · 갱신 0명" }).click();
  await expect(admin.getByRole("heading", { name: "명부를 반영했습니다" })).toBeVisible({ timeout: 120_000 });
  const refreshed = admin.waitForResponse((r) => r.request().method() === "GET" && new URL(r.url()).pathname === "/api/v1/me/action-inbox");
  await go(admin, "/");
  expect((await refreshed).status()).toBe(200);
  await expect(rail).toContainText("미배치 18");
  const counts = await read<{ summary: { people: number; placed: number; unplaced: number } }>("/api/v1/onboarding/checklist");
  expect(counts.summary).toMatchObject({ people: 2000, placed: 1982, unplaced: 18 });
  await expect(admin.getByText("일괄 작업", { exact: true })).toBeVisible();
  for (const name of ["조직 시트 가져오기", "목록 붙여넣기", "조직 시트 내려받기", "설정 단계 기록"]) await expect(admin.getByRole("main").getByText(name, { exact: true }).last()).toBeVisible();
  await inviteAccount(admin, "테스트 사용자", "none");
  await grantSetupRole(admin, "테스트 사용자", "명부 관리", true);
  await go(admin, "/");
  const roles = steps.filter({ hasText: "역할 · 담당자 초대" });
  await expect(roles).toHaveAttribute("data-state", "done");
  await expectAccessible(admin, "ideal rail 2000 people prepared role");
  await probeActions(admin);
  await admin.screenshot({ path: info.outputPath("rail-2000.png"), fullPage: true });
  await go(admin, "/setup/go-live");
  const breakdown = admin.getByRole("table", { name: "법인 · 사업장별 인원" });
  await expect(breakdown).toContainText("1,982");
  await expect(breakdown.getByRole("row").filter({ hasText: "사업장 · 본사" }).getByRole("cell").nth(2)).toHaveText("2"); // 본사 and the setup 부서
  await expect(admin.getByRole("table", { name: "운영 시작부터 적용되는 역할" })).toContainText("테스트 사용자");
  await expect(admin.getByRole("main")).toContainText("준비된 권한 1건");
});

test("BL-013 bulk paths keep legal facts and lock a pending employee paste read", { tag: ["@first-run", "@regression"] }, async ({ browser }) => {
  const admin = await soloTenant(browser, "ideal-paste", "목록그룹");
  await setupRail(admin).getByRole("link", { name: "목록 붙여넣기" }).first().click();
  await admin.getByRole("textbox", { name: "법인 목록" }).fill("법인 이름\t종류\t대표자\t대표 방식\n목록개인\tINDIVIDUAL\t김대표\tJOINT");
  await admin.getByRole("button", { name: "열 연결", exact: true }).click();
  await admin.getByRole("button", { name: "입력값 확인" }).click();
  const preview = admin.getByRole("button", { name: "등록 미리보기" });
  await expect(preview).toHaveAttribute("aria-disabled", "true");
  const mode = admin.getByRole("radiogroup", { name: /^대표 방식/ });
  await chooseRadio(mode, /^단독대표$/);
  await preview.click();
  await admin.getByRole("button", { name: "기록 1건 반영" }).click();
  await expect(admin.getByRole("status").filter({ hasText: "기록 1건을 반영했습니다" }).first()).toBeVisible();
  await probeActions(admin);
  await go(admin, "/people/import?mode=paste");
  await admin.getByRole("textbox", { name: "직원 목록" }).fill("성명\t사번\t입사일\n목록직원\tP-1\t2025-01-01");
  let release!: () => void;
  const gate = new Promise<void>((ok) => { release = ok; });
  await admin.route("**/api/v1/employees/import/preview", async (r) => { await gate; await r.continue(); });
  // The source must stay bound to the in-flight preview even if someone tries to edit it.
  await admin.getByRole("button", { name: "명부 미리보기" }).click();
  await expect(admin.getByRole("textbox", { name: "직원 목록" })).toBeDisabled();
  release();
  await expect(admin.getByRole("button", { name: "모의 반영 실행" })).toBeVisible({ timeout: 30_000 });
  await admin.getByRole("button", { name: "모의 반영 실행" }).click();
  const applied = admin.waitForResponse((r) => r.request().method() === "POST" && /\/employees\/import\/[^/]+\/apply$/.test(r.url()));
  await admin.getByRole("button", { name: "명부 반영: 신규 1명 · 갱신 0명" }).click();
  expect([200, 202]).toContain((await applied).status());
  await expect(admin.getByRole("heading", { name: "명부를 반영했습니다" })).toBeVisible();
});
