import { expect, test } from "@playwright/test";
import { expectAccessible } from "./a11y";
import { apiAs, soloTenant } from "./chaos";
import { firstSignIn, go } from "./flows";
import { inviteAccount } from "./access-flows";
import { homeRail, setupCompany, setupRail } from "./setup-flows";
import { grantSetupRole, probeActions } from "./helpers/first-run";

test("BL-015: lazy exact terms refuse a wrong hash and acceptance resolves in place", { tag: ["@first-run", "@negative"] }, async ({ browser }, info) => {
  const admin = await soloTenant(browser, "ideal-terms", "약관그룹");
  const read = apiAs(admin);
  await setupCompany(admin, "약관정밀", "본사");
  let reads = 0;
  admin.on("request", (r) => { if (new URL(r.url()).pathname === "/api/v1/onboarding/terms" && r.method() === "GET") reads++; });
  await go(admin, "/setup/go-live");
  await expect(admin.getByRole("heading", { name: "운영 시작", level: 1 })).toBeVisible();
  expect(reads).toBe(0);
  await admin.getByRole("button", { name: "이용약관 읽기" }).click();
  await expect(admin.getByText("E2E service terms fixture. This is a test document, not a published contract.", { exact: true })).toBeVisible();
  await expect(admin.getByRole("term").filter({ hasText: /^버전$/ }).locator("..").getByRole("definition")).toHaveText("e2e-v1");
  const document = await read<{ version: string; sha256: string; body: string }>("/api/v1/onboarding/terms");
  await expect(admin.getByRole("main")).toContainText(document.sha256);
  await admin.route("**/api/v1/onboarding/terms", async (r) => {
    if (r.request().method() !== "POST") return r.fallback();
    const body = r.request().postDataJSON();
    await r.continue({ postData: JSON.stringify({ ...body, sha256: "0".repeat(64) }) });
  });
  const refused = admin.waitForResponse((r) => new URL(r.url()).pathname === "/api/v1/onboarding/terms" && r.request().method() === "POST");
  const accept = admin.getByRole("button", { name: "고객 계정을 대표해 이용약관 동의" });
  await accept.click();
  const response = await refused;
  expect(response.status()).toBe(409);
  expect((await response.json()).error.code).toBe("terms_text_changed");
  await expect(admin.getByRole("alert").filter({ hasText: "새 내용을 읽고 동의" }).last()).toBeVisible();
  const preview = await read<{ blockers: { code: string }[] }>("/api/v1/onboarding/go-live/preview");
  expect(preview.blockers.some((b) => b.code === "terms_not_accepted")).toBe(true);
  await expect(accept).toBeVisible();
  await admin.unroute("**/api/v1/onboarding/terms");
  await expect(accept).toBeEnabled();
  await accept.click();
  await expect(accept).toBeHidden();
  await expect(admin.getByText("해결함", { exact: true })).toBeVisible();
  expect((await read<{ blockers: { code: string }[] }>("/api/v1/onboarding/go-live/preview")).blockers.some((b) => b.code === "terms_not_accepted")).toBe(false);
  await expectAccessible(admin, "ideal terms accepted in place");
  await probeActions(admin);
  await admin.screenshot({ path: info.outputPath("terms-resolved.png"), fullPage: true });
});

test("BL-017: HR with no grant is refused; an employees setup grant gives a read-only legal-entity step", { tag: ["@first-run", "@access", "@negative"] }, async ({ browser }, info) => {
  const admin = await soloTenant(browser, "ideal-viewer", "담당그룹");
  await setupCompany(admin, "담당정밀", "본사");
  const hr = await firstSignIn(browser, await inviteAccount(admin, "김인사", "none"));
  await expect(setupRail(hr)).toHaveCount(0);
  const denied = hr.waitForResponse((r) => new URL(r.url()).pathname === "/api/v1/me/action-inbox");
  await hr.reload();
  const deniedInbox = await denied;
  expect(deniedInbox.status()).toBe(200);
  expect((await deniedInbox.json()).setup).toBeUndefined();
  await grantSetupRole(admin, "김인사", "직원 설정", false);
  await hr.reload();
  const rail = await homeRail(hr);
  await expect(rail).toBeVisible();
  const legal = rail.locator("[data-step]").filter({ hasText: "법인 등록" }).first();
  await expect(legal).toContainText("조직 등록·수정 권한 필요");
  await expect(legal.getByRole("link")).toHaveCount(0);
  await expect(rail.getByRole("link", { name: "직원 등록", exact: true })).toBeVisible();
  await expect(rail.locator("[data-step]").filter({ hasText: "운영 시작" }).last()).toContainText("운영 계정 필요");
  await expect(rail.getByRole("link", { name: "운영 시작", exact: true })).toHaveCount(0);
  await expectAccessible(hr, "ideal per-viewer rail");
  await probeActions(hr);
  await hr.screenshot({ path: info.outputPath("employees-only-rail.png"), fullPage: true });
  await hr.context().setOffline(true);
  await expect(hr.getByText("실시간 연결 끊김 · 재연결 중", { exact: true })).toBeVisible({ timeout: 20_000 });
  await expect(rail).toBeVisible();
  await expect(legal).toContainText("조직 등록·수정 권한 필요");
  await hr.context().setOffline(false);
  await expect(hr.getByText("실시간 연결 끊김 · 재연결 중", { exact: true })).toBeHidden({ timeout: 20_000 });
  await go(admin, "/");
  await expect(await homeRail(admin)).toBeVisible();
});
