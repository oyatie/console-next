import { expect, test } from "@playwright/test";
import { atPhoneWidth, expectAccessible, fits } from "./a11y";
import { go, kstDate, registerEmployee } from "./flows";
import { prepareFilingCompletion, selectFilingFact } from "./helpers/statutory";
import { staffedTenant } from "./setup-flows";
import { addDays } from "../apps/web/src/ui/date/days";

test("statutory filings and a dated worker register from an empty tenant", { tag: "@hr" }, async ({ browser }) => {
  const { admin } = await staffedTenant(browser, "statutory", "법정서류회사");
  await go(admin, "/statutory");
  await expect(admin.getByText("신고할 항목이 없습니다", { exact: true })).toBeVisible();
  await expect(admin.getByText("직원에서 입사·퇴직·휴직·복직 기록을 확인하십시오.", { exact: true })).toBeVisible();
  await expect(admin.getByRole("link", { name: "직원 열기" })).toHaveAttribute("href", "/people");
  await admin.getByRole("tab", { name: "근로자 명부" }).click();
  await expect(admin.getByText("사업장을 선택하거나 조직 구조에서 사업장을 등록하십시오.", { exact: true })).toBeVisible();
  await expect(admin.getByRole("link", { name: "조직 구조 열기" })).toHaveAttribute("href", "/org");
  await expect(admin.getByRole("main")).not.toContainText("사업장별 근로자 명부를 조회합니다");
  await expectAccessible(admin, "statutory empty states with next actions");
  const hiredOn = kstDate(-20);
  await registerEmployee(admin, { name: "김신고", number: "S-1", hired: hiredOn });
  await go(admin, "/statutory");
  await expect(admin.getByRole("heading", { name: "법정 신고·서류" })).toBeVisible();
  await expect(admin.getByRole("tab")).toHaveCount(2);
  const row = admin.getByRole("row").filter({ hasText: "김신고" }).filter({ hasText: "국민연금" });
  await expect(row).toContainText("취득 신고");
  await expect(admin.getByRole("columnheader", { name: "사번", exact: true })).toBeVisible();
  await expect(admin.getByRole("columnheader", { name: "사업장", exact: true })).toBeVisible();
  await expect(row).toContainText("S-1");
  await expect(row).toContainText("노무사 검토 전");
  await expectAccessible(admin, "insurance filings");
  await atPhoneWidth(admin, () => fits(admin, "insurance filings"));
  const latestRead = (url: URL) => url.pathname.endsWith("/insurance-filings") && url.searchParams.has("event_id");
  await admin.route(latestRead, (route) => route.abort("failed"));
  await row.getByRole("button", { name: "처리 기록" }).click();
  const dialog = admin.getByRole("dialog");
  await expect(dialog).toContainText("불러오지 못했습니다", { timeout: 15_000 });
  await expect(dialog.getByRole("button", { name: "신고 완료", exact: true })).toHaveCount(0);
  await admin.unroute(latestRead);
  await dialog.getByRole("button", { name: "다시 불러오기" }).click();
  await selectFilingFact(admin, dialog, "처리 방법", "신고 완료");
  await dialog.getByRole("textbox", { name: /^신고일/ }).fill(kstDate());
  await dialog.getByRole("button", { name: "미리보기" }).click();
  const unverified = admin.waitForResponse((r) => r.request().method() === "POST" && r.url().includes("/insurance-filings/"));
  await dialog.getByRole("button", { name: "신고 완료", exact: true }).click();
  const refusal = await unverified;
  expect(refusal.status()).toBe(422);
  expect((await refusal.json()).error.code).toBe("filing_applicability_unverified");
  await expect(dialog.getByRole("alert").last()).toContainText("신고 적용 사실을 확인하지 않아 저장하지 않았습니다");
  await expect(row).toContainText("해야 함");
  await dialog.getByRole("button", { name: "수정", exact: true }).click();
  await prepareFilingCompletion(admin, dialog);
  await dialog.getByRole("textbox", { name: /^신고일/ }).fill("");
  await dialog.getByRole("button", { name: "미리보기" }).click();
  await expect(dialog).toContainText("신고일을 확인하십시오");
  await expect(row).toContainText("해야 함");
  await dialog.getByRole("textbox", { name: /^신고일/ }).fill(kstDate());
  await dialog.getByLabel(/^접수번호/).fill("batch-101");
  await dialog.getByRole("button", { name: "미리보기" }).click();
  await expect(dialog).toContainText("업무함과 홈에서 완료로 표시");
  await expectAccessible(admin, "filing completion preview");
  await dialog.getByRole("button", { name: "신고 완료", exact: true }).click();
  await expect(dialog).toBeHidden();
  await expect(admin.getByRole("status").filter({ hasText: "완료를 기록했습니다" })).toBeVisible();
  await admin.getByRole("button", { name: "처리 내역", exact: true }).first().click();
  await expect(row).toContainText("batch-101");
  await row.getByRole("button", { name: "되돌리기" }).click();
  await expect(admin.getByRole("status").filter({ hasText: "완료 기록을 되돌렸습니다" })).toBeVisible();
  await admin.getByRole("button", { name: "해야 함", exact: true }).click();
  await expect(row).toContainText("해야 함");
  await row.getByRole("button", { name: "처리 기록" }).click();
  await prepareFilingCompletion(admin, dialog);
  await dialog.getByRole("textbox", { name: /^신고일/ }).fill(kstDate());
  await dialog.getByRole("button", { name: "미리보기" }).click();
  const peer = await admin.context().newPage();
  await go(peer, "/statutory");
  const peerRow = peer.getByRole("row").filter({ hasText: "김신고" }).filter({ hasText: "국민연금" });
  await peerRow.getByRole("button", { name: "처리 기록" }).click();
  const peerDialog = peer.getByRole("dialog");
  await prepareFilingCompletion(peer, peerDialog);
  await peerDialog.getByRole("textbox", { name: /^신고일/ }).fill(kstDate());
  await peerDialog.getByLabel(/^접수번호/).fill("peer-202");
  await peerDialog.getByRole("button", { name: "미리보기" }).click();
  await peerDialog.getByRole("button", { name: "신고 완료", exact: true }).click();
  await expect(peerDialog).toBeHidden();
  await dialog.getByRole("button", { name: "신고 완료", exact: true }).click();
  await expect(dialog).toContainText("완료 증빙이 변경되어 저장하지 않았습니다");
  await expect(dialog).toContainText("peer-202");
  await expect(dialog.getByRole("button", { name: "신고 완료", exact: true })).toBeDisabled();
  await dialog.getByRole("button", { name: "최신 목록 확인" }).click();
  await admin.getByRole("button", { name: "처리 내역", exact: true }).first().click();
  await row.getByRole("button", { name: "되돌리기" }).click();
  await admin.getByRole("button", { name: "해야 함", exact: true }).click();
  await expect(row).toContainText("해야 함");
  await peer.close();
  await go(admin, "/people");
  await go(admin, "/people?export=register", true);
  await expect(admin.getByRole("heading", { name: "근로자 명부 내보내기" })).toBeVisible();
  await admin.getByRole("radiogroup", { name: /사업장/ }).getByText(/본사/).click();
  await admin.getByRole("radiogroup", { name: /왜 내보냅니까/ }).getByText("감사 대응", { exact: true }).click();
  const legacyDownload = admin.getByRole("button", { name: "명부 내려받기", exact: true });
  await expect(legacyDownload).toHaveAttribute("aria-disabled", "true");
  await expect(admin.getByText(/사업장·용도·개인 정보 방식.*내려받습니다/)).toBeVisible();
  await expect(admin.getByRole("radiogroup", { name: "개인 정보 필수", exact: true })).toBeVisible();
  await expect(admin.getByRole("radio", { name: /^주소·생년월일 가리기/ })).toBeDisabled();
  await expect(admin.getByText("근로자 1명 (재직·휴직) + 퇴직 0명", { exact: true })).toBeVisible();
  await expect(admin.getByRole("table", { name: "명부 미리 보기" })).toContainText("김신고");
  const legacyRequests: string[] = [];
  admin.on("request", (request) => { if (new URL(request.url()).pathname.endsWith("/employees/export.csv")) legacyRequests.push(request.url()); });
  await legacyDownload.click({ force: true });
  await expect(admin.getByRole("radiogroup", { name: "개인 정보 필수", exact: true }).getByRole("radio").first()).toBeFocused();
  expect(legacyRequests, "a missing privacy choice must not dispatch an export").toEqual([]);
  await expect(legacyDownload).toHaveAttribute("aria-disabled", "true");
  await admin.getByRole("radiogroup", { name: "개인 정보 필수", exact: true }).getByText("명부 항목 전체 포함", { exact: true }).click();
  const csv = admin.waitForEvent("download");
  await legacyDownload.click();
  expect((await csv).suggestedFilename()).toMatch(/\.csv$/);
  await admin.getByRole("button", { name: "닫고 직원 목록으로", exact: true }).click();
  await expect(admin).toHaveURL(/\/people$/);
  await go(admin, "/");
  const filings = admin.getByRole("region", { name: "업무함", exact: true }).getByRole("listitem").filter({ has: admin.getByRole("link", { name: "4대보험 신고 열기", exact: true }) });
  await expect(filings).toHaveCount(4);
  for (const insurer of ["국민연금", "건강보험", "고용보험", "산재보험"]) {
    const filing = filings.filter({ hasText: insurer });
    await expect(filing).toContainText("김신고");
    await expect(filing).toContainText("취득 신고");
    await expect(filing.getByRole("link", { name: "4대보험 신고 열기", exact: true })).toBeVisible();
  }
  await filings.first().getByRole("link", { name: "4대보험 신고 열기", exact: true }).click();
  await admin.getByRole("tab", { name: "근로자 명부" }).click();
  await admin.getByRole("button", { name: /사업장/ }).click();
  await admin.getByRole("option", { name: /본사/ }).click();
  await expect(admin.getByRole("table", { name: "근로자 명부" })).toContainText("S-1");
  await expect(admin.getByRole("link", { name: /김신고 · 주소 확인 필요/ })).toHaveAttribute("href", /act=fix%3Aaddress/);
  await expectAccessible(admin, "worker register with nonblocking gaps");
  await atPhoneWidth(admin, () => fits(admin, "worker register"));
  await admin.getByRole("button", { name: "xlsx 내보내기" }).click();
  await expect(admin.getByText("용도를 선택하십시오", { exact: false })).toBeVisible();
  await admin.getByRole("button", { name: /내보내기 용도/ }).click();
  await admin.getByRole("option").filter({ hasText: "감사" }).click();
  const downloaded = admin.waitForEvent("download");
  await admin.getByRole("button", { name: "xlsx 내보내기" }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.xlsx$/);
  await admin.addInitScript(() => {
    window.print = () => { window.parent.document.documentElement.dataset.registerPrinted = document.querySelector("tbody")?.textContent ?? ""; };
  });
  await admin.getByRole("button", { name: "PDF 저장·인쇄" }).click();
  await expect.poll(() => admin.locator("html").getAttribute("data-register-printed")).toContain("S-1");
  await expect.poll(() => admin.locator("html").getAttribute("data-register-printed")).toContain("김신고");
  await admin.getByRole("textbox", { name: /^기준일/ }).fill(addDays(hiredOn, -1));
  await admin.getByRole("textbox", { name: /^기준일/ }).blur();
  await expect(admin.getByText("이 기준일의 근로자 명부가 없습니다", { exact: true })).toBeVisible();
  await admin.getByRole("textbox", { name: /^기준일/ }).fill(kstDate());
  await admin.getByRole("textbox", { name: /^기준일/ }).blur();
  await admin.getByRole("link", { name: /김신고 · 주소 확인 필요/ }).click();
  await expect(admin.getByRole("dialog")).toBeVisible();
  await expect(admin.getByRole("dialog")).toContainText("주소");
});
