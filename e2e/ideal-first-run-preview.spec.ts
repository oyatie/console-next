// Each journey begins with an empty UI-created tenant and only its contracting administrator.
test("BL-014: unplaced is a warning, stale preview re-arms, and operating Home keeps placement", { tag: "@first-run" }, async ({ browser }, info) => {
  test.setTimeout(180_000);
  const admin = await soloTenant(browser, "ideal-preview", "미리보기그룹");
  const read = apiAs(admin);
  await setupCompany(admin, "미리보기정밀", "본사");
  await go(admin, "/people/import");
  await chooseWorkbook(admin, "미배치.xlsx", await workbook([plain("미리보기정밀", Array.from({ length: 18 }, (_, i) => ({ name: `미배치${i + 1}`, number: `UP-${i + 1}`, hired: kstDate(-30) })))]));
  await admin.getByRole("button", { name: "명부 미리보기" }).click();
  await admin.getByRole("button", { name: "모의 반영 실행" }).click();
  await admin.getByRole("button", { name: "명부 반영: 신규 18명 · 갱신 0명" }).click();
  await expect(admin.getByRole("heading", { name: "명부를 반영했습니다" })).toBeVisible();
  await go(admin, "/setup/go-live");
  let showTerms!: () => void;
  const termsGate = new Promise<void>((ok) => { showTerms = ok; });
  await admin.route("**/api/v1/onboarding/terms", async (r) => {
    if (r.request().method() === "GET") await termsGate;
    await r.continue();
  });
  await admin.getByRole("button", { name: "이용약관 읽기" }).click();
  const placement = admin.getByRole("link", { name: "배치", exact: true }).first();
  const loadingY = (await placement.boundingBox())!.y;
  showTerms();
  const accept = admin.getByRole("button", { name: "고객 계정을 대표해 이용약관 동의" });
  await expect(accept).toBeVisible();
  expect(Math.abs((await placement.boundingBox())!.y - loadingY)).toBeLessThan(2);
  const readY = (await placement.boundingBox())!.y;
  await accept.click();
  await expect(accept).toBeHidden();
  expect(Math.abs((await placement.boundingBox())!.y - readY)).toBeLessThan(2);
  await admin.unroute("**/api/v1/onboarding/terms");
  await expect(admin.getByRole("button", { name: "고객 계정을 대표해 이용약관 동의" })).toBeHidden();
  const warning = admin.getByRole("main").getByText("미배치 18명 · 운영 시작 후에도 배치할 수 있습니다", { exact: true });
  await expect(warning).toBeVisible();
  await expect(admin.getByRole("link", { name: "배치", exact: true }).first()).toBeVisible();
  await expect(admin.getByRole("grid", { name: "권한 관리 담당자" })).toContainText(/.+/);
  await expectAccessible(admin, "ideal preview unplaced warning");
  await probeActions(admin);
  let release!: () => void;
  let hit!: () => void;
  const submitted = new Promise<void>((ok) => { hit = ok; });
  const gate = new Promise<void>((ok) => { release = ok; });
  await admin.route("**/api/v1/onboarding/go-live", async (r) => { hit(); await gate; await r.continue(); });
  await admin.getByRole("button", { name: "운영 시작", exact: true }).click();
  await submitted;
  // A real concurrent UI write happens after the immutable go-live request was sent.
  const other = await admin.context().newPage();
  await other.goto("/access/roles/new");
  await other.getByRole("textbox", { name: /^역할 이름/ }).fill("동시 등록 역할");
  await other.getByRole("button", { name: "인사기본 조회" }).click();
  await other.getByRole("button", { name: "역할 추가" }).click();
  await expect(other).toHaveURL(/\/access\/roles$/);
  const refusal = admin.waitForResponse((r) => new URL(r.url()).pathname === "/api/v1/onboarding/go-live" && r.request().method() === "POST");
  release();
  const response = await refusal;
  expect(response.status()).toBe(409);
  expect((await response.json()).error.code).toBe("preview_stale");
  await expect(admin.getByRole("alert").filter({ hasText: "바뀐 항목을 다시 확인" })).toBeVisible();
  expect((await read<{ phase: string }>("/api/v1/onboarding/checklist")).phase).toBe("SETUP");
  await expect(admin.getByRole("button", { name: "운영 시작", exact: true })).toBeEnabled();
  await admin.screenshot({ path: info.outputPath("stale-preview.png"), fullPage: true });
  await admin.unroute("**/api/v1/onboarding/go-live");
  await admin.getByRole("button", { name: "운영 시작", exact: true }).click();
  await expect(admin).toHaveURL(/\/$/);
  await expect(admin.getByRole("main")).toContainText("미배치");
  await expect(admin.getByText("운영 시작 · 되돌리기 → 정정", { exact: true })).toBeVisible();
  await admin.screenshot({ path: info.outputPath("operating-home-unplaced.png"), fullPage: true });
});

test("BL-016: setup and seven-day operating bands persist across routes in a keyboard walk", { tag: "@first-run" }, async ({ browser }, info) => {
  const admin = await soloTenant(browser, "ideal-phase", "단계그룹");
  await expect(admin.getByText("설정 단계 · 운영 시작 전", { exact: true })).toBeVisible();
  const keyboard = { click: keyboardActivate };
  const { registerEntity, registerWorkplace } = await import("./setup-flows");
  await keyboardActivate(setupRail(admin).getByRole("link", { name: "법인 등록" }).first());
  await registerEntity(admin, "단계정밀", false, keyboard);
  await go(admin, "/");
  await keyboardActivate(setupRail(admin).getByRole("link", { name: "사업장 등록" }).first());
  await registerWorkplace(admin, "단계정밀", "본사", false, keyboard);
  await go(admin, "/");
  await keyboardActivate(setupRail(admin).getByRole("link", { name: "부서 추가" }).first());
  await addDepartments(admin, "본사", ["단계지원팀"]);
  await go(admin, "/");
  await keyboardActivate(setupRail(admin).getByRole("button", { name: "직원은 나중에" }));
  await keyboardActivate(setupRail(admin).getByRole("button", { name: "담당자는 나중에" }));
  await expect(setupRail(admin)).toContainText("운영 시작 후에도 운영 계정 혼자 처리합니다");
  await admin.screenshot({ path: info.outputPath("setup-band.png"), fullPage: true });
  await startOperations(admin, false, keyboard);
  await expect(admin.getByText("운영 시작 · 되돌리기 → 정정", { exact: true })).toBeVisible();
  await go(admin, "/people");
  await expect(admin.getByText("운영 시작 · 되돌리기 → 정정", { exact: true })).toBeVisible();
  await expectAccessible(admin, "ideal operating phase band");
  await probeActions(admin);
  await admin.screenshot({ path: info.outputPath("operating-band.png"), fullPage: true });
});
