import ExcelJS from "exceljs";
import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { expectAccessible } from "../a11y";
import { firstSignIn, go } from "../flows";
import { openTenant } from "../helpers/tenant";
import { chooseWorkbook } from "../helpers/import";
import { apiOf, bearerOf } from "../helpers/api";
import { registerEntity } from "../setup-flows";
import { firstWorkplace } from "../helpers/entity";
import { inviteAccount } from "../access-flows";

async function source() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("인사 명부");
  ws.addRow(["회사와 등록증 자료", "", "", "", "직원 자료"]);
  ws.mergeCells("A1:D1");
  ws.addRow(["회사", "법인", "상호", "대표자", "성명", "사번", "입사일", "고용형태"]);
  ws.addRow(["GANATECH", "주식회사 가나테크", "주식회사 가나테크", "김예시,박예시", "김직원", "CN-001", "2026-01-01", "정규직"]);
  ws.addRow(["김예시,박예시", "", "", "김예시,박예시", "이직원", "CN-002", "2026-01-01", "정규직"]);
  return Buffer.from(await wb.xlsx.writeBuffer());
}

test("merged workbook company cells remain an explicit source queue and create no legal entities", { tag: ["@hr", "@regression"] }, async ({ browser }) => {
  const p = await openTenant(browser, "company-source", "가져오기 검증");
  const api = apiOf(p, bearerOf(p));
  await go(p, "/people/import");
  await chooseWorkbook(p, "회사_대표자_명부.xlsx", await source());
  await p.getByRole("button", { name: "명부 미리보기" }).click();
  await p.getByRole("button", { name: "모의 반영 실행" }).click();
  const alias = p.getByRole("grid", { name: "값 연결 · 소속 이름 후보" }).getByRole("row", { name: /^김예시,박예시/ });
  await expect(alias).toBeVisible();
  await alias.click();
  await expect(p.getByRole("region", { name: "소속 이름 확인 필요" })).toContainText("회사 값 “김예시,박예시”");
  await expect(p.getByText(/A4/).first()).toBeVisible();
  await expectAccessible(p, "company alias confirmation source");
  // A stale/forged employer choice reaches the real guard and keeps the source review intact.
  const dryRoute = /\/employees\/import\/[\w-]+\/dry-run$/;
  await p.route(dryRoute, async (r) => {
    const body = r.request().postDataJSON();
    const keys = Object.keys(body.decisions.company_map);
    expect(keys).toHaveLength(1);
    await r.fallback({ postData: JSON.stringify({ ...body, decisions: { ...body.decisions, company_map: { [keys[0]!]: randomUUID() } } }) });
  });
  const refusal = p.waitForResponse((r) => dryRoute.test(r.url()) && r.request().method() === "POST");
  await p.getByRole("region", { name: "소속 이름 확인 필요" }).getByText("확인 필요로 유지", { exact: true }).click();
  const response = await refusal;
  expect(response.status()).toBe(422);
  expect(JSON.stringify(await response.json())).toContain("entity_certificate_unconfirmed");
  await expect(p.getByRole("alert")).toContainText("등록증으로 확인된 법인만 연결할 수 있습니다");
  expect((await (await api("/employees?limit=10")).json()).items).toHaveLength(0);
  await expect(p.getByText(/A4/).first()).toBeVisible();
  await expectAccessible(p, "company candidate refusal retains source");
  await p.unroute(dryRoute);
  await p.getByRole("button", { name: "선택한 내용으로 다시 모의 반영" }).click();
  await expect(p.getByRole("alert")).toHaveCount(0);
  await p.getByRole("button", { name: "명부 반영: 신규 2명 · 갱신 0명" }).click();
  await expect(p.getByRole("heading", { name: "명부를 반영했습니다" })).toBeVisible({ timeout: 60_000 });
  expect((await (await api("/legal-entities")).json()).items).toHaveLength(0);
  const people = (await (await api("/employees?limit=10")).json()).items as { name: string; company: string }[];
  expect(people.map((person) => person.name).sort()).toEqual(["김직원", "이직원"]);
  expect(people.every((person) => !["GANATECH", "김예시,박예시"].includes(person.company))).toBe(true);
  const reconcile = p.getByRole("group", { name: /^행별 대조/ });
  await reconcile.getByRole("row").filter({ hasText: "이직원" }).click();
  await expect(reconcile).toContainText("파일 소속 값 “김예시,박예시”");
  await expect(reconcile).toContainText("A4");
  await expect(reconcile).toContainText("열 “회사”");
  const checkReply = p.waitForResponse((r) => r.request().method() === "PUT" && /\/reconcile\/rows\//.test(r.url()));
  await reconcile.getByRole("button", { name: "맞음", exact: true }).click();
  const check = await checkReply;
  expect(check.status()).toBe(422);
  expect(JSON.stringify(await check.json())).toContain("entity_certificate_unconfirmed");
  await expect(reconcile.getByRole("alert")).toContainText("등록증으로 확인된 법인만 연결할 수 있습니다");
  await expect(reconcile).toContainText("파일 소속 값 “김예시,박예시”");
  await expectAccessible(p, "applied company confirmation queue retains source and refusal");
  const completed = new URL(p.url());
  expect(completed.searchParams.get("run")).toBeTruthy();
  const reviewPath = completed.pathname + completed.search;
  await p.reload();
  await reconcile.getByRole("row").filter({ hasText: "이직원" }).click();
  await expect(reconcile).toContainText("파일 소속 값 “김예시,박예시”");
  const other = await openTenant(browser, "company-other", "다른 고객");
  const otherRead = other.waitForResponse((r) => r.request().method() === "GET" && r.url().endsWith("/reconcile"));
  await go(other, reviewPath);
  expect((await otherRead).status()).toBe(404);
  await expect(other.getByRole("alert")).toBeVisible();
  await expect(other.getByText("김예시,박예시", { exact: true })).toHaveCount(0);
  await expect(other.getByRole("button", { name: "맞음", exact: true })).toHaveCount(0);
  await expectAccessible(other, "other tenant cannot see imported company evidence");
  const lower = await firstSignIn(browser, await inviteAccount(p, "가져오기 읽기 제한", "none"));
  const lowerRead = lower.waitForResponse((r) => r.request().method() === "GET" && r.url().endsWith("/reconcile"));
  await go(lower, reviewPath);
  expect((await lowerRead).status()).toBe(403);
  await expect(lower.getByRole("heading", { name: "접근 권한이 없습니다" }).first()).toBeVisible();
  await expect(lower.getByRole("button", { name: "맞음", exact: true })).toHaveCount(0);
  await expectAccessible(lower, "lower grant cannot open imported company confirmation");
  await go(p, "/org/entities/new");
  await registerEntity(p, "가나테크");
  await firstWorkplace(p, "가나테크", "본사");
  await go(p, "/people/unplaced");
  await p.getByRole("grid", { name: "미배치 처리" }).getByRole("row").filter({ hasText: "이직원" }).click();
  await p.getByRole("button", { name: "사업장 직속 배치" }).click();
  await expect(p.getByRole("status").filter({ hasText: "1명 배치 끝" })).toBeVisible();
  await go(p, reviewPath);
  // The queue re-reads once the placement event lands; select the row on the settled read.
  await expect(async () => {
    await reconcile.getByRole("row").filter({ hasText: "이직원" }).click();
    await expect(reconcile).toContainText("직원의 법인: 주식회사 가나테크", { timeout: 1_000 });
  }).toPass();
  const confirmedReply = p.waitForResponse((r) => r.request().method() === "PUT" && /\/reconcile\/rows\//.test(r.url()));
  await reconcile.getByRole("button", { name: "맞음", exact: true }).click();
  expect((await confirmedReply).status()).toBe(200);
  await expect(reconcile.getByRole("row").filter({ hasText: "이직원" })).toContainText("맞음");
  await expectAccessible(p, "certificate-confirmed employer settles an imported source row");
  await p.reload();
  await expect(reconcile.getByRole("row").filter({ hasText: "이직원" })).toContainText("맞음");
  await p.getByRole("link", { name: "다른 명부 가져오기" }).click();
  await expect(p.getByRole("button", { name: "명부 미리보기" })).toBeVisible();
});
