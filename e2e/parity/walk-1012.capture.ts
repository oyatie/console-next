test("parity 1012: solo rail, exact terms, real stale launch and day one", async ({ browser }) => {
  test.setTimeout(180_000);
  const a = await openTenant(browser, "parity-home-1012", "패리티첫운영");
  const rail = setupRail(a);
  await expect(rail.locator("[data-step]")).toHaveCount(7);
  await rail.locator("[data-step]").first().focus();
  await a.keyboard.press("j");
  await expect(rail.locator("[data-step]").nth(1)).toBeFocused();
  await a.keyboard.press("k");
  await expect(rail.locator("[data-step]").first()).toBeFocused();
  await capture(a, "home-first-run", ["H1-setup-empty", "H1-master-setup", "S1-home"], "Fresh empty solo tenant; seven derived rail steps and J/K focus. No drafts, import or scoped-view fixture.");
  await inspect(a, "home-first-run", "empty-1012");
  await setupCompany(a, "패리티첫운영", "본사");
  await go(a, "/people/new");
  await fillRegister(a, { name: "미배치직원", hired: kstDate(-20) });
  await pressRegister(a);
  await expect(receiptOf(a, "미배치직원")).toBeVisible();
  await go(a, "/");
  await expect(rail).toContainText("미배치 1");
  await go(a, "/setup/go-live");
  await expect(a.getByRole("alert", { name: "고객 계정의 이용약관 동의가 없습니다" })).toBeVisible();
  await capture(a, "home-first-run", ["P6-golive-preview", "P6-golive-migration-warning"], "Real launch review: one entity/site/person, unplaced warning, terms blocker, per-site counts and ops access holder. No migrated data.");
  await a.route("**/api/v1/onboarding/terms", (r) => r.request().method() === "GET" ? r.fulfill({ status: 500, body: "" }) : r.continue());
  await a.getByRole("button", { name: "이용약관 읽기" }).click();
  await expect(a.getByRole("button", { name: "다시 불러오기", exact: true })).toBeVisible();
  await expect(a.getByRole("button", { name: "고객 계정을 대표해 이용약관 동의" })).toHaveCount(0);
  await scene(a, "terms-read-error");
  await a.unroute("**/api/v1/onboarding/terms");
  await a.getByRole("button", { name: "다시 불러오기", exact: true }).click();
  const accept = a.getByRole("button", { name: "고객 계정을 대표해 이용약관 동의" });
  await expect(accept).toBeVisible();
  await capture(a, "home-first-run", ["P5-consent-text"], "Exact current version/hash/body on the go-live review; this is the terms ancestor, not the first-sign-in enrollment fixture.");
  const version = await a.getByRole("term").filter({ hasText: /^버전$/ }).locator("..").getByRole("definition").innerText();
  const sha256 = await a.getByRole("term").filter({ hasText: /^SHA-256$/ }).locator("..").getByRole("definition").innerText();
  let accepted: { version: string; sha256: string } | null = null;
  await a.route("**/api/v1/onboarding/terms", async (r) => {
    if (r.request().method() === "POST") accepted = r.request().postDataJSON();
    await r.continue();
  });
  await accept.click();
  await expect(accept).toBeHidden();
  expect(accepted).toEqual({ version, sha256 });
  await a.unroute("**/api/v1/onboarding/terms");
  await go(a, "/");
  await go(a, "/setup/go-live");
  await expect(a.getByRole("button", { name: "이용약관 읽기" })).toHaveCount(0);
  await inspect(a, "home-first-run", "launch-1012");
  let release!: () => void;
  let submitted!: () => void;
  const gate = new Promise<void>((ok) => { release = ok; });
  const hit = new Promise<void>((ok) => { submitted = ok; });
  await a.route("**/api/v1/onboarding/go-live", async (r) => { submitted(); await gate; await r.continue(); });
  await a.getByRole("button", { name: "운영 시작", exact: true }).click();
  await hit;
  const other = await a.context().newPage();
  await go(other, "/access/roles/new");
  await other.getByRole("textbox", { name: /^역할 이름/ }).fill("동시 등록 역할");
  await other.getByRole("button", { name: "인사기본 조회", exact: true }).click();
  await other.getByRole("button", { name: "역할 만들기" }).click();
  await expect(other).toHaveURL(/\/access\/roles$/);
  const refusal = a.waitForResponse((r) => r.url().endsWith("/onboarding/go-live") && r.request().method() === "POST");
  release();
  const response = await refusal;
  expect(response.status()).toBe(409);
  expect((await response.json()).error.code).toBe("preview_stale");
  await expect(a.getByRole("alert").filter({ hasText: "바뀐 항목을 다시 확인" })).toBeVisible();
  await expect(a.getByText("설정 단계 · 운영 시작 전", { exact: true })).toBeVisible();
  await capture(a, "home-first-run", ["H3-launch-conflict", "P6-golive-stale"], "Fresh real preview_stale409 after concurrent UI-created role; setup retained, terms acceptance retained, latest preview re-arms. Role count changed; same-count mutation is not proved.");
  await a.unroute("**/api/v1/onboarding/go-live");
  await other.close();
  await startOperations(a);
  await capture(a, "home-first-run", ["H4-launch-receipt", "P7-day1-home", "P7-golive-done", "H5-deadline"], "Actual post-launch Home with one unplaced worker; phase success, not an immutable launch receipt or complete statutory agenda.");
  await inspect(a, "home-first-run", "operating-1012");
});

test("parity 1012: Home loading, failed producer and denied producer", async ({ browser }) => {
  const a = await openTenant(browser, "parity-home-reads-1012", "패리티읽기");
  await setupCompany(a, "패리티읽기", "본사");
  await startOperations(a);
  const api = /\/api\/v1\/me\/action-inbox(?:\?|$)/;
  let release!: () => void;
  let called!: () => void;
  const gate = new Promise<void>((ok) => { release = ok; });
  const hit = new Promise<void>((ok) => { called = ok; });
  await a.route(api, async (r) => { called(); await gate; await r.continue(); });
  await a.reload();
  await hit;
  await capture(a, "home-first-run", ["H11-loading", "S1-loading"], "Controlled GET delay with zero employees; honest loading, no fabricated counts or source writes.");
  const loaded = a.waitForResponse((r) => api.test(r.url()) && r.status() === 200);
  release();
  await loaded;
  await a.unroute(api);
  await a.route(api, (r) => r.fulfill({ status: 500, body: "" }));
  await a.reload();
  await expect(a.getByRole("alert").filter({ hasText: "일부 항목을 불러오지 못했습니다" })).toBeVisible();
  await capture(a, "home-first-run", ["H6-source-error"], "Controlled GET500; rendering probe only. Real other producers continue. No last-good timestamp fixture.");
  await inspect(a, "home-first-run", "failed-read-1012");
  await a.unroute(api);
  const denied = /\/api\/v1\/hr\/exit-cases(\?|$)/;
  await a.route(denied, (r) => r.fulfill({ status: 403, contentType: "application/json", body: JSON.stringify({ error: { code: "forbidden", message: "forbidden" } }) }));
  await a.reload();
  await expect(a.getByRole("region", { name: "일부 항목은 볼 권한이 없습니다" })).toBeVisible();
  await capture(a, "home-first-run", ["H8-permission"], "Controlled GET403; safe permission notice rendering, not real Cedar revocation/cache purge proof.");
  await a.unroute(denied);
});
