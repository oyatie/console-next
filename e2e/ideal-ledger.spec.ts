import { expect, test } from "@playwright/test";
import { expectAccessible } from "./a11y";
import { inviteAccount } from "./access-flows";
import { faultNext, sent } from "./chaos";
import { chooseRadio, firstSignIn, go } from "./flows";
import { openTenant } from "./helpers/tenant";
import { acceptSetupTerms, setupCompany } from "./setup-flows";

const GO_LIVE = /\/api\/v1\/onboarding\/go-live$/;
const APPLY_GRANTS = /\/api\/v1\/access\/grants\/apply$/;
const OUTCOME = /\/api\/v1\/requests\/[^/]+$/;
const REMEDY = "다시 제출하기 전에 원래 요청의 결과를 확인하십시오.";

test("BL-010 a lost go-live response checks the original APPLIED outcome without a second command", { tag: ["@org", "@chaos", "@ledger"] }, async ({ browser }) => {
  const admin = await openTenant(browser, "ledger-live", "원장운영");
  await setupCompany(admin, "원장운영", "본점");
  await go(admin, "/setup/go-live");
  await expect(admin.getByRole("heading", { name: "운영 시작", level: 1 })).toBeVisible();
  const start = admin.getByRole("button", { name: "운영 시작", exact: true });
  await expect(start).toBeVisible();
  await acceptSetupTerms(admin);
  const sole = admin.getByLabel(/본인뿐인 채로 운영을 시작합니다/);
  if (await sole.isVisible()) await sole.check();
  await expect(start).toBeEnabled();
  const commands = sent(admin, GO_LIVE);
  await faultNext(admin, GO_LIVE, "lost");
  await start.focus();
  await admin.keyboard.press("Enter");
  const checking = admin.getByRole("status").filter({ hasText: "처리 여부 확인 중" });
  await expect(checking).toBeVisible();
  await expect(checking).toContainText(REMEDY);
  await expect(start).toBeDisabled();
  await admin.keyboard.press("Enter");
  expect(commands.count()).toBe(1);
  expect([...commands.keys()]).toEqual([expect.stringMatching(/^[0-9a-f-]{36}$/)]);
  await expectAccessible(admin, "BL-010 lost go-live: checking state");

  const link = checking.getByRole("link", { name: "요청 결과 보기", exact: true });
  const key = [...commands.keys()][0]!;
  await expect(link).toHaveAttribute("href", `/requests/${key}`);
  const response = admin.waitForResponse((r) => OUTCOME.test(new URL(r.url()).pathname) && r.request().method() === "GET");
  await link.focus();
  await admin.keyboard.press("Enter");
  const res = await response;
  expect(res.status()).toBe(200);
  const outcome = await res.json();
  expect(outcome).toMatchObject({ state: "APPLIED", idempotency_key: key, masked: false });
  expect(outcome.result.go_live_at).toBeTruthy();
  await expect(admin).toHaveURL(new RegExp(`/requests/${key}$`));
  await expect(admin.getByRole("heading", { name: "요청 결과", level: 1 })).toBeVisible();
  await expect(admin.getByRole("status").filter({ hasText: /^반영됨$/ })).toBeVisible();
  await expect(admin.getByText(outcome.id, { exact: true })).toBeVisible();
  await expect(admin.getByRole("heading", { name: "처리 결과", exact: true })).toBeVisible();
  await expectAccessible(admin, "BL-010 APPLIED go-live outcome");
  await admin.reload();
  await expect(admin.getByRole("status").filter({ hasText: /^반영됨$/ })).toBeVisible();
  expect(commands.count()).toBe(1);
});

test("BL-010 grant apply loses its response, preserves the receipt and is recorded once", { tag: ["@access", "@chaos", "@ledger"] }, async ({ browser }) => {
  const admin = await openTenant(browser, "ledger-grant", "원장권한");
  await firstSignIn(browser, await inviteAccount(admin, "김원장", "none"));
  await go(admin, "/access/roles/new");
  await admin.getByRole("textbox", { name: /^역할 이름/ }).fill("원장 조회");
  await admin.getByRole("button", { name: "인사기본 조회", exact: true }).click();
  await admin.getByRole("button", { name: "역할 추가", exact: true }).click();
  await expect(admin.getByRole("row", { name: /원장 조회/ })).toBeVisible();
  await go(admin, "/access/grants");
  await admin.getByRole("button", { name: "권한 부여", exact: true }).click();
  await admin.getByRole("combobox", { name: "권한을 부여할 사람 (이름 또는 사번)" }).fill("김원장");
  await admin.getByRole("option", { name: /김원장/ }).click();
  const sheet = admin.getByRole("dialog", { name: "권한 부여" });
  await sheet.getByRole("button", { name: / 역할$/ }).click();
  await admin.getByRole("option", { name: /^원장 조회/ }).click();
  await sheet.getByRole("button", { name: /범위 선택/ }).click();
  const scope = admin.getByRole("dialog", { name: "범위 선택" });
  await scope.getByRole("row", { name: /^전체/ }).click();
  await scope.getByRole("button", { name: "이 범위로 설정" }).click();
  await sheet.getByRole("button", { name: /^1년/ }).click();
  await chooseRadio(sheet, /^설정 단계부터/);
  await chooseRadio(sheet, /^업무 배정·변경/);
  const apply = sheet.getByRole("button", { name: "패스키로 확인하고 부여 1건 저장", exact: true });
  const commands = sent(admin, APPLY_GRANTS);
  const previews = sent(admin, /\/api\/v1\/access\/grants\/preview$/);
  await faultNext(admin, APPLY_GRANTS, "lost");
  await apply.click();
  const checking = sheet.getByRole("status").filter({ hasText: "처리 여부 확인 중" });
  await expect(checking).toBeVisible();
  await expect(checking).toContainText(REMEDY);
  await expect(apply).toBeDisabled();
  await admin.keyboard.press("Enter");
  expect(commands.count()).toBe(1);
  expect(previews.count()).toBe(1);
  await expectAccessible(admin, "BL-010 lost grant apply: checking state");

  const key = [...commands.keys()][0]!;
  expect(key).toMatch(/^[0-9a-f-]{36}$/);
  const link = checking.getByRole("link", { name: "요청 결과 보기", exact: true });
  await expect(link).toHaveAttribute("href", `/requests/${key}`);
  const response = admin.waitForResponse((r) => OUTCOME.test(new URL(r.url()).pathname) && r.request().method() === "GET");
  await link.focus();
  await admin.keyboard.press("Enter");
  const res = await response;
  expect(res.status()).toBe(200);
  const outcome = await res.json();
  expect(outcome).toMatchObject({ state: "APPLIED", idempotency_key: key, masked: false });
  expect(outcome.result.items).toHaveLength(1);
  expect(outcome.result.operation_id).toBe(outcome.id);
  await expect(admin.getByRole("status").filter({ hasText: /^반영됨$/ })).toBeVisible();
  await expectAccessible(admin, "BL-010 APPLIED grant receipt");
  await go(admin, "/access/grants");
  const grant = admin.getByRole("row", { name: /김원장/ }).filter({ hasText: "원장 조회" });
  await expect(grant).toHaveCount(1);
  await expect(grant).toContainText("적용 중");
  expect(commands.count()).toBe(1);
  expect(previews.count()).toBe(1);
});

test("BL-010 invalid and missing lookup keys show their refusal and a correction remedy", { tag: ["@ledger", "@regression"] }, async ({ browser }) => {
  const admin = await openTenant(browser, "ledger-lookup", "원장조회");
  await go(admin, "/requests");
  const input = admin.getByRole("textbox", { name: /^요청 번호 또는 요청 키/ });
  const find = admin.getByRole("button", { name: "결과 확인", exact: true });
  const reads = sent(admin, OUTCOME, "GET");
  await expect(input).toBeVisible();
  await input.fill("short");
  await expect(find).toHaveAttribute("aria-disabled", "true");
  await expect(find).toHaveAttribute("aria-describedby", /.+/);
  await find.focus();
  await admin.keyboard.press("Enter");
  await expect(input).toBeFocused();
  await expect(input).toHaveAccessibleDescription("요청 번호는 16~200자로 입력하십시오.");
  await expect(find).toHaveAccessibleDescription("요청 번호는 16~200자로 입력하십시오.");
  await input.press("Enter");
  expect(reads.count()).toBe(0);

  const missing = "missing-ledger-request-key";
  await input.fill(missing);
  const missingResponse = admin.waitForResponse((r) => new URL(r.url()).pathname === `/api/v1/requests/${missing}`);
  await find.focus();
  await admin.keyboard.press("Enter");
  const missingRes = await missingResponse;
  expect(missingRes.status()).toBe(404);
  expect((await missingRes.json()).error.code).toBe("request_not_found");
  await expect(admin.getByRole("heading", { name: "요청을 찾을 수 없습니다. 요청 번호와 조회 권한을 확인하십시오.", exact: true })).toBeVisible();
  await expect(admin.getByText(REMEDY)).toBeVisible();
  await expectAccessible(admin, "BL-010 missing request remedy");
  await admin.getByRole("link", { name: "요청 번호 또는 요청 키", exact: true }).first().click();
  await expect(input).toHaveValue("");

  const malformedResponse = admin.waitForResponse((r) => new URL(r.url()).pathname === "/api/v1/requests/short");
  await go(admin, "/requests/short");
  const malformedRes = await malformedResponse;
  expect(malformedRes.status()).toBe(422);
  expect((await malformedRes.json()).error.code).toBe("invalid_request_key");
  await expect(admin.getByRole("alert")).toBeVisible();
  const remedy = admin.getByRole("link", { name: "요청 번호 또는 요청 키", exact: true });
  await expect(remedy).toBeVisible();
  expect(reads.count()).toBe(2);
  await expectAccessible(admin, "BL-010 malformed request remedy");
  await remedy.focus();
  await admin.keyboard.press("Enter");
  await expect(input).toBeVisible();
  expect(reads.count()).toBe(2);
});
