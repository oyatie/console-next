import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, globSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = resolve(root, "apps/web/src/generated/fonts");
const source = "node_modules/pretendard/dist/web/variable/woff2/PretendardVariable.woff2";
const descriptors = "node_modules/pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css";
const lock = "apps/web/font-subsets.requirements.txt";
// Shared boot plus the first surface: structure heads and their date controls.
const catalogs = globSync(["boot*.ts", "{ko,en}/{structure,structure-chart,asof,ui-date,ui-org-canvas}.ts"], { cwd: resolve(root, "packages/i18n/src/catalogs") })
  .map(file => `packages/i18n/src/catalogs/${file}`).sort();
const read = file => readFileSync(resolve(root, file));
const hash = data => createHash("sha256").update(data).digest("hex");

export function catalogCharacters(files = catalogs) {
  // Dynamic dates and counts can contain any decimal digit.
  const characters = new Set(Array.from({ length: 10 }, (_, i) => String(i)));
  for (const file of files) {
    const tree = ts.createSourceFile(file, read(file).toString(), ts.ScriptTarget.Latest, true);
    const visit = node => {
      if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.initializer)) {
        for (const c of node.initializer.text) characters.add(c);
      }
      ts.forEachChild(node, visit);
    };
    visit(tree);
  }
  return [...characters].map(c => c.codePointAt(0)).sort((a, b) => a - b);
}

const inputs = () => Object.fromEntries(["scripts/font-subsets.mjs", lock, source, descriptors].map(file => [file, hash(read(file))]));
const generated = "/* SPDX-License-Identifier: LicenseRef-Proprietary */\n/* Generated by scripts/font-subsets.mjs --write. */\n/* stylelint-disable scale-unlimited/declaration-strict-value -- Font matching requires literal face metadata. */\n";
const regenerate = "Font catalog inputs changed; run npm run fonts:generate -w @console/web";
function verifyCoverage(requested) {
  if (!requested || catalogCharacters().some(c => !requested.includes(c))) throw new Error(regenerate);
}
function verifyOutputs(manifest) {
  for (const [file, digest] of Object.entries(manifest.outputs)) {
    if (hash(readFileSync(resolve(out, file))) !== digest) throw new Error(`Font subset is corrupt: ${file}`);
  }
}
export function check() {
  const manifest = JSON.parse(readFileSync(resolve(out, "manifest.json"), "utf8"));
  if (JSON.stringify(manifest.inputs) !== JSON.stringify(inputs())) throw new Error(regenerate);
  verifyCoverage(manifest.requested);
  verifyOutputs(manifest);
  return manifest;
}

function refreshInputs() {
  const manifest = JSON.parse(readFileSync(resolve(out, "manifest.json"), "utf8"));
  const current = inputs();
  // Upgrade hash-only manifests only when the original generation-time set can be proven.
  const requested = manifest.requested ?? (manifest.inputs.catalogCharacters === hash(JSON.stringify(catalogCharacters())) ? catalogCharacters() : undefined);
  // Refresh provenance after a generator edit only when every requested glyph is already covered.
  if ([lock, source, descriptors].some(file => manifest.inputs[file] !== current[file])) throw new Error(regenerate);
  verifyCoverage(requested);
  verifyOutputs(manifest);
  writeFileSync(resolve(out, "manifest.json"), JSON.stringify({ ...manifest, inputs: current, requested }, null, 2) + "\n");
}

function generate() {
  const env = resolve(root, ".cache/font-subsetter");
  const python = resolve(env, "bin/python");
  if (!existsSync(python)) execFileSync(process.env.PYTHON ?? "python3", ["-m", "venv", env], { stdio: "inherit" });
  execFileSync(python, ["-m", "pip", "install", "--disable-pip-version-check", "--no-cache-dir", "--require-hashes", "--only-binary=:all:", "--no-deps", "-r", resolve(root, lock)], { stdio: "inherit" });
  mkdirSync(out, { recursive: true });
  const requested = catalogCharacters();
  const unicodes = requested.map(c => `U+${c.toString(16)}`).join(",");
  execFileSync(python, ["-m", "fontTools.subset", resolve(root, source), `--unicodes=${unicodes}`, "--flavor=woff2", `--output-file=${resolve(out, "catalog.woff2")}`], { stdio: "inherit" });
  // Use the actual cmap: unsupported catalog symbols must retain system fallback.
  const metadata = [
    "import json,sys; from fontTools.ttLib import TTFont",
    "f=TTFont(sys.argv[1])",
    "print(json.dumps(dict(cmap=sorted(f.getBestCmap()),family=f['name'].getDebugName(16) or f['name'].getDebugName(1))))",
  ].join("\n");
  const { cmap, family } = JSON.parse(execFileSync(python, ["-c", metadata, resolve(out, "catalog.woff2")], { encoding: "utf8" }));
  const catalogFamily = `${family} Catalog`;
  const weight = read(descriptors).toString().match(/font-weight:\s*([^;]+);/)[1];
  const css = generated + `:root { --font-catalog: ${JSON.stringify(catalogFamily)}, ${JSON.stringify(family)}; }\n@font-face { font-family: ${JSON.stringify(catalogFamily)}; font-weight: ${weight}; font-style: normal; font-display: optional; src: url("./catalog.woff2") format("woff2-variations"); unicode-range: ${cmap.map(c => `U+${c.toString(16)}`).join(",")}; }\n`;
  writeFileSync(resolve(out, "catalog.css"), css);
  const outputs = Object.fromEntries(["catalog.woff2", "catalog.css"].map(file => [file, hash(readFileSync(resolve(out, file)))]));
  writeFileSync(resolve(out, "manifest.json"), JSON.stringify({ inputs: inputs(), outputs, family: catalogFamily, codepoints: cmap, requested }, null, 2) + "\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === "--write") generate();
  else if (process.argv[2] === "--refresh-inputs") refreshInputs();
  else if (process.argv[2] !== "--check") throw new Error("Usage: font-subsets.mjs --write|--check|--refresh-inputs");
  check();
  process.stdout.write("font subsets: catalog inputs and generated assets verified\n");
}
